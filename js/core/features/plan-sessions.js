// Plan-owned sessions (TP-4) — the plan's workouts live with the plan.
//
// Kevin: "Templates should be centric to the training plan, but if I like a
// rotation, let me save it to my workout list. Don't overwhelm that list."
// A workout the coach builds FOR the plan carries `planOwned: true, planId`;
// the Workouts list shows the user's own workouts, and a "Your plan" group on
// top shows this week's plan sessions (whoever owns them) with Start. "Save
// to my workouts" clones a plan session into the list; later rotations touch
// the plan's copy only. A plan session no week uses any more is archived.
//
// Hand-built workouts never become plan-owned: a program links them on its
// split, but ownership only comes from building a workout for the plan.
//
// Pure. Imports only mirrored siblings.
//
// MIRRORED: functions/plan-sessions.js is generated by
//   node scripts/sync-mirror.mjs js/core/features/plan-sessions.js functions/plan-sessions.js
// (tests/unit/movement-patterns-mirror.test.js enforces parity).

import { addDays } from './block-view.js';
import { DAY_KEYS, mondayOf } from './plan-timeline.js';

const DAY_LABELS = { mon: 'Mon', tue: 'Tue', wed: 'Wed', thu: 'Thu', fri: 'Fri', sat: 'Sat', sun: 'Sun' };
export const PLAN_ID = 'current';

export const isPlanOwned = (t) => !!t?.planOwned;

/** The Workouts list: the user's own active workouts; plan sessions and archived ones apart. */
export function splitTemplatesForList(templates = []) {
    const list = templates || [];
    return {
        mine: list.filter(t => !t.archived && !isPlanOwned(t)),
        plan: list.filter(t => !t.archived && isPlanOwned(t)),
        archived: list.filter(t => t.archived),
    };
}

/**
 * This week's plan sessions in day order (Mon–Sun), from the week plan —
 * each with its date, whether it's today, and whether it was done.
 * @returns {Array<{day, dayLabel, date, isToday, done, template}>}
 */
export function planWeekSessions({ weekPlan = null, templates = [], workouts = [], today }) {
    const byId = new Map((templates || []).map(t => [t.id, t]));
    const monday = mondayOf(today);
    const out = [];
    DAY_KEYS.forEach((d, i) => {
        const id = weekPlan?.days?.[d];
        if (!id || id === 'rest') return;
        const t = byId.get(id);
        if (!t || t.archived) return;
        const date = addDays(monday, i);
        const done = (workouts || []).some(w => w?.date === date && w.completedAt && !w.cancelledAt
            && (w.basedOn === t.id || String(w.workoutType || '').toLowerCase() === String(t.name || '').toLowerCase()));
        out.push({ day: d, dayLabel: DAY_LABELS[d], date, isToday: date === today, done, template: t });
    });
    return out;
}

const slug = (s) => String(s || 'workout').replace(/[^a-zA-Z0-9]/g, '_').toLowerCase();

/**
 * "Save to my workouts": a copy of a plan session in the user's own list.
 * The explicit save is the intent, so no near-duplicate check applies.
 * @returns {object} the new template doc (id included)
 */
export function cloneForMyWorkouts(template, { name = null, date, stamp = Date.now() } = {}) {
    const title = String(name || '').trim() || `${template.name || 'Workout'} (saved)`;
    const { id: _id, planOwned: _po, planId: _pid, archived: _a, lastUsed: _lu, usageCount: _uc, ...rest } = template || {};
    return {
        ...rest,
        id: `${slug(title)}_${Number(stamp).toString(36)}`,
        name: title,
        kind: 'core',
        planOwned: false,
        savedFromPlan: { templateId: template.id, planId: template.planId || PLAN_ID, date },
        exercises: (template.exercises || []).map(e => ({ ...e })),
        createdVia: 'save-from-plan',
    };
}

/**
 * Plan sessions to archive: plan-owned, still active, and used by no
 * planned day any more — not the week plan, not the split of any wave that
 * hasn't ended. They stay for history (workouts reference them); the
 * archived group hides them.
 */
export function planTemplatesToArchive({ templates = [], weekPlan = null, programs = [], today }) {
    const used = new Set(Object.values(weekPlan?.days || {}).filter(v => v && v !== 'rest'));
    for (const p of programs || []) {
        if (!p?.startDate || p.state === 'undone') continue;
        const end = addDays(p.startDate, Math.max(1, Number(p.weeks) || 1) * 7 - 1);
        if (end < today) continue;
        for (const v of Object.values(p.split || {})) if (v && v !== 'rest') used.add(v);
    }
    return (templates || []).filter(t => isPlanOwned(t) && !t.archived && !used.has(t.id)).map(t => t.id);
}

/** The coach's `Plan sessions:` line — listed through the plan, outside the saved-workouts cap. */
export function formatPlanSessionsContext({ templates = [], weekPlan = null, today }) {
    const owned = splitTemplatesForList(templates).plan;
    if (!owned.length) return '';
    const thisWeek = new Set(planWeekSessions({ weekPlan, templates, today }).map(s => s.template.id));
    const names = owned.map(t => `${t.name || t.id}${thisWeek.has(t.id) ? '' : ' (not on this week)'}`);
    return `Plan sessions (built for the plan; the user's own list stays separate — "save to my workouts" copies one there): ${names.join(', ')}\n`;
}
