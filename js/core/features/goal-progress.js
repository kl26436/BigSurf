// Goal progress (TP-1) — "am I on track?" in code, not in the model.
//
// A goal is a target with a baseline the APP captured at creation (never
// typed): a lift's estimated max, a 7-day bodyweight average, a scan's lean
// mass or body fat, days a week, or weekly sets for a movement pattern. This
// module validates goals (the add-goal sheet and the coach's set_goal share
// it), measures where the user is now, and says ahead / on track / behind /
// met with the rate math and one plain sentence. The coach quotes the
// sentence; the Goals page shows it; the Sunday report card lists it.
//
// Pure. Imports only mirrored siblings.
//
// MIRRORED: functions/goal-progress.js is generated by
//   node scripts/sync-mirror.mjs js/core/features/goal-progress.js functions/goal-progress.js
// (tests/unit/movement-patterns-mirror.test.js enforces parity).

import { bestE1rmBetween, buildScoreboard, PATTERN_LABELS } from './progress-scoreboard.js';
import { weightIncrement } from './progression.js';
import { PATTERNS } from './movement-patterns.js';
import { weightAverage, scanLeanMass, scanBodyFatPct, scansAsOf, shiftDate, daysBetween } from './body-stats.js';

export const GOAL_TYPES = ['lift', 'bodyweight', 'composition', 'consistency', 'balance'];
export const GOAL_METRICS = {
    lift: ['estimatedMax'],
    bodyweight: ['weight'],
    composition: ['leanMass', 'bodyFatPct'],
    consistency: ['daysPerWeek'],
    balance: ['patternSets'],
};
export const GOAL_STATUSES = ['active', 'met', 'missed', 'paused'];
export const EVENT_KINDS = ['look', 'perform', 'other'];

/** Weeks of history a lift's estimated max is read over (the scoreboard's window). */
export const LIFT_WINDOW_DAYS = 28;
/** On track = the projection lands within this share of the target. */
export const ON_TRACK_SHARE = 0.025;
/** Open-ended goals report progress against this horizon. */
export const OPEN_HORIZON_WEEKS = 12;

const ISO = /^\d{4}-\d{2}-\d{2}$/;
const round1 = (n) => Math.round(n * 10) / 10;
const round2 = (n) => Math.round(n * 100) / 100;
const clip = (s, n) => String(s || '').trim().slice(0, n);
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

/** "Feb 14" — deterministic, no locale. */
export function shortDate(iso) {
    if (!iso || !ISO.test(iso)) return '';
    const [, m, d] = iso.split('-').map(Number);
    return `${MONTHS[m - 1]} ${d}`;
}

const unitOf = (u) => (u === 'kg' ? 'kg' : 'lbs');

// ── Validation (the sheet and set_goal share it) ────────────────────

/**
 * Normalize + validate a goal draft. Rejects with the allowed values
 * (AP-18: reject, don't coerce). `mainLifts` (names) gates lift goals when
 * the user has chosen them; `events` (ids) gates eventId.
 * @returns {{ok: true, goal: object} | {ok: false, error: string, hint?: string}}
 */
export function normalizeGoal(input, { today, mainLifts = [], eventIds = [], unit = 'lbs' } = {}) {
    const type = String(input?.type || '').trim();
    if (!GOAL_TYPES.includes(type)) return { ok: false, error: `type must be one of ${GOAL_TYPES.join(', ')} (got ${JSON.stringify(input?.type)})` };
    const metric = input.metric || GOAL_METRICS[type][0];
    if (!GOAL_METRICS[type].includes(metric)) return { ok: false, error: `metric for a ${type} goal must be one of ${GOAL_METRICS[type].join(', ')} (got ${JSON.stringify(metric)})` };
    const target = Number(input.target);
    if (!Number.isFinite(target) || target <= 0) return { ok: false, error: `target must be a positive number (got ${JSON.stringify(input.target)})` };

    const goal = { type, metric, target: round2(target), key: null, unit: null, direction: null };
    if (type === 'lift') {
        const exercise = clip(input.key?.exercise ?? input.exercise, 80);
        if (!exercise) return { ok: false, error: 'a lift goal needs key.exercise (the lift\'s name)' };
        if (mainLifts.length) {
            const hit = mainLifts.find(n => n.toLowerCase() === exercise.toLowerCase());
            if (!hit) return { ok: false, error: `"${exercise}" isn't one of the main lifts.`, hint: `Main lifts: ${mainLifts.join(', ')}. Pick one, or set it as a main lift first (set_primary_lifts).` };
            goal.key = { exercise: hit, machine: clip(input.key?.machine, 80) || null, machineId: clip(input.key?.machineId, 80) || null };
        } else {
            goal.key = { exercise, machine: clip(input.key?.machine, 80) || null, machineId: clip(input.key?.machineId, 80) || null };
        }
        goal.unit = unitOf(input.unit || unit);
        goal.direction = 'up';
    } else if (type === 'bodyweight') {
        goal.unit = unitOf(input.unit || unit);
        goal.direction = input.direction === 'up' || input.direction === 'down' ? input.direction : null; // inferred from baseline
    } else if (type === 'composition') {
        goal.key = metric === 'leanMass' ? 'totalLeanMass' : 'bodyFatPct';
        goal.unit = metric === 'leanMass' ? unitOf(input.unit || unit) : '%';
        if (metric === 'bodyFatPct' && target >= 60) return { ok: false, error: `body fat target is a percentage under 60 (got ${target})` };
        goal.direction = metric === 'leanMass' ? 'up' : 'down';
        if (input.direction === 'up' || input.direction === 'down') goal.direction = input.direction;
    } else if (type === 'consistency') {
        if (target > 7) return { ok: false, error: `days a week is 1–7 (got ${target})` };
        goal.unit = 'days/week';
        goal.direction = 'up';
    } else if (type === 'balance') {
        const pattern = String(input.key?.pattern ?? input.pattern ?? input.key ?? '').trim();
        if (!PATTERNS.includes(pattern)) return { ok: false, error: `a balance goal needs key.pattern, one of ${PATTERNS.join(', ')} (got ${JSON.stringify(pattern)})` };
        if (target > 40) return { ok: false, error: `weekly sets is 1–40 (got ${target})` };
        goal.key = { pattern };
        goal.unit = 'sets/week';
        goal.direction = 'up';
    }

    const by = input.by == null || input.by === '' ? null : String(input.by);
    if (by && !ISO.test(by)) return { ok: false, error: `by must be a YYYY-MM-DD date or null (got ${JSON.stringify(input.by)})` };
    if (by && today && by <= today) return { ok: false, error: `by must be after today (${today}) — got ${by}` };
    goal.by = by;
    const eventId = input.eventId ? String(input.eventId) : null;
    if (eventId && eventIds.length && !eventIds.includes(eventId)) return { ok: false, error: `eventId ${eventId} not found`, hint: 'Call list_goals for the event ids, or add_event first.' };
    goal.eventId = eventId;
    goal.name = clip(input.name, 60) || null;
    goal.note = clip(input.note, 200) || null;
    goal.status = 'active';
    return { ok: true, goal };
}

/** Normalize + validate an event draft. */
export function normalizeEvent(input, { today } = {}) {
    const name = clip(input?.name, 60);
    if (!name) return { ok: false, error: 'an event needs a name' };
    const date = String(input?.date || '');
    if (!ISO.test(date)) return { ok: false, error: `date must be YYYY-MM-DD (got ${JSON.stringify(input?.date)})` };
    if (today && date <= today) return { ok: false, error: `the event date must be after today (${today}) — got ${date}` };
    const kind = input.kind || 'other';
    if (!EVENT_KINDS.includes(kind)) return { ok: false, error: `kind must be one of ${EVENT_KINDS.join(', ')} (got ${JSON.stringify(input.kind)})` };
    const peakWeeks = input.peakWeeks == null ? 2 : Number(input.peakWeeks);
    if (!Number.isInteger(peakWeeks) || peakWeeks < 0 || peakWeeks > 4) return { ok: false, error: `peakWeeks is 0–4 (got ${JSON.stringify(input.peakWeeks)})` };
    return {
        ok: true,
        event: { name, date, kind, note: clip(input.note, 200) || null, peakWeeks, lighterBefore: input.lighterBefore !== false },
    };
}

/** An active goal that measures the same thing (type, metric, lift / pattern) — one per thing. */
export function findSameGoal(goal, goals = []) {
    const key = (g) => JSON.stringify([g.type, g.metric, g.key?.exercise?.toLowerCase?.() ?? g.key?.pattern ?? g.key ?? null]);
    return (goals || []).find(g => g && g.status === 'active' && key(g) === key(goal)) || null;
}

// ── Measuring ───────────────────────────────────────────────────────

/** Distinct training days a week, averaged over the 4 weeks ending `today`. */
export function daysPerWeek(workouts, today, weeks = 4) {
    const from = shiftDate(today, -(weeks * 7 - 1));
    const days = new Set((workouts || []).filter(w => w?.date && w.completedAt && !w.cancelledAt && w.date >= from && w.date <= today).map(w => w.date));
    return round1(days.size / weeks);
}

/**
 * Where the user is now on one goal, by its type — the same rules as the
 * scoreboard (lifts), the body-weight page (7-day average) and the scans.
 * @returns {{now: number|null, nowDate: string|null, source: string, sinceScan?: number|null}}
 */
export function measureGoal(goal, { workouts = [], templates = [], measurements = [], dexa = [], today, plates = null } = {}) {
    const u = goal.unit === 'kg' ? 'kg' : 'lbs';
    if (goal.type === 'lift') {
        const machine = goal.key?.machine || goal.key?.machineId ? { name: goal.key.machine || null, id: goal.key.machineId || null } : null;
        const v = bestE1rmBetween(workouts, goal.key.exercise, u, shiftDate(today, -(LIFT_WINDOW_DAYS - 1)), today, machine);
        return { now: v == null ? null : round1(v), nowDate: today, source: 'lift' };
    }
    if (goal.type === 'bodyweight') {
        const a = weightAverage(measurements, { asOf: today, unit: u });
        return { now: a ? a.value : null, nowDate: a ? today : null, source: 'weight7' };
    }
    if (goal.type === 'composition') {
        const scan = scansAsOf(dexa, today)[0] || null;
        if (!scan) return { now: null, nowDate: null, source: 'scan' };
        const now = goal.metric === 'leanMass' ? scanLeanMass(scan, u) : scanBodyFatPct(scan);
        // Between scans, bodyweight is the proxy (§TP-1): the change since the scan.
        const wNow = weightAverage(measurements, { asOf: today, unit: u });
        const wThen = weightAverage(measurements, { asOf: scan.date, unit: u });
        const sinceScan = wNow && wThen && scan.date < today ? round1(wNow.value - wThen.value) : null;
        return { now, nowDate: scan.date, source: 'scan', sinceScan, weightUnit: u };
    }
    if (goal.type === 'consistency') {
        return { now: daysPerWeek(workouts, today), nowDate: today, source: 'days' };
    }
    if (goal.type === 'balance') {
        const sb = buildScoreboard({ workouts, templates, unit: u, today, config: { increment: weightIncrement(u, plates) } });
        const row = sb.patterns.find(p => p.pattern === goal.key?.pattern);
        return { now: row ? row.setsThisWeek : 0, nowDate: today, source: 'pattern' };
    }
    return { now: null, nowDate: null, source: 'unknown' };
}

/**
 * The baseline a new goal stores — measured from the data, never typed.
 * Also fills a bodyweight goal's direction from it.
 * @returns {{baseline: {value, date}|null, direction: 'up'|'down'}}
 */
export function captureBaseline(goal, data) {
    const m = measureGoal(goal, data);
    const baseline = m.now == null ? null : { value: m.now, date: m.nowDate || data.today };
    let direction = goal.direction;
    if (!direction) direction = baseline && goal.target < baseline.value ? 'down' : 'up';
    return { baseline, direction };
}

// ── Status ──────────────────────────────────────────────────────────

/** The on-track tolerance around a target, in the goal's own unit. */
export function toleranceOf(goal, { plates = null } = {}) {
    if (goal.type === 'consistency') return 0.25;
    if (goal.type === 'balance') return 1;
    const share = Math.abs(goal.target) * ON_TRACK_SHARE;
    if (goal.type === 'lift') return Math.max(share, weightIncrement(goal.unit === 'kg' ? 'kg' : 'lbs', plates));
    return share;
}

const crossed = (goal, v) => (goal.direction === 'down' ? v <= goal.target : v >= goal.target);

/**
 * @param {object} goal - stored goal (with baseline)
 * @param {{now, nowDate, source, sinceScan?}} measured - from measureGoal
 * @param {string} today
 * @returns {{status: 'ahead'|'on-track'|'behind'|'met'|'missed'|'no-date'|'too-early'|'no-data'|'paused',
 *   pct: number|null, requiredRate: number|null, actualRate: number|null, projected: number|null,
 *   weeksLeft: number|null, now: number|null, sentence: string}}
 */
export function goalStatus(goal, measured, today, { plates = null } = {}) {
    const now = measured?.now ?? null;
    const base = goal.baseline?.value ?? null;
    const out = { status: 'no-data', pct: null, requiredRate: null, actualRate: null, projected: null, weeksLeft: null, now };
    if (goal.status === 'paused') return finish(goal, { ...out, status: 'paused' }, measured, today);
    if (now == null) return finish(goal, out, measured, today);

    // Rolling goals (days a week, weekly sets) are a standing bar, not a climb.
    if (goal.type === 'consistency' || goal.type === 'balance') {
        const tol = toleranceOf(goal, { plates });
        const status = now >= goal.target ? 'met' : (now >= goal.target - tol ? 'on-track' : 'behind');
        return finish(goal, { ...out, status, pct: Math.min(100, Math.round((now / goal.target) * 100)) }, measured, today);
    }

    const span = base != null ? goal.target - base : null;
    out.pct = span ? Math.max(0, Math.min(100, Math.round(((now - base) / span) * 100))) : null;
    if (crossed(goal, now)) return finish(goal, { ...out, status: 'met', pct: 100 }, measured, today);
    if (goal.by && today > goal.by) return finish(goal, { ...out, status: 'missed' }, measured, today);
    if (base == null || !goal.baseline?.date) return finish(goal, { ...out, status: goal.by ? 'too-early' : 'no-date' }, measured, today);

    const weeksElapsed = daysBetween(goal.baseline.date, measured.nowDate || today) / 7;
    out.actualRate = weeksElapsed >= 1 ? round2((now - base) / weeksElapsed) : null;
    if (!goal.by) return finish(goal, { ...out, status: out.actualRate == null ? 'too-early' : 'no-date' }, measured, today);

    const weeksTotal = Math.max(daysBetween(goal.baseline.date, goal.by) / 7, 1 / 7);
    out.weeksLeft = round1(Math.max(0, daysBetween(today, goal.by) / 7));
    out.requiredRate = round2((goal.target - base) / weeksTotal);
    if (out.actualRate == null) return finish(goal, { ...out, status: 'too-early' }, measured, today);
    // Scan-based goals project from the scan date, not today.
    const weeksFromNow = Math.max(0, daysBetween(measured.nowDate || today, goal.by) / 7);
    out.projected = round1(now + out.actualRate * weeksFromNow);
    const tol = toleranceOf(goal, { plates });
    const gap = goal.direction === 'down' ? goal.target - out.projected : out.projected - goal.target;
    out.status = Math.abs(gap) <= tol ? 'on-track' : (gap > 0 ? 'ahead' : 'behind');
    out.slightly = out.status === 'behind' && Math.abs(gap) <= tol * 2;
    return finish(goal, out, measured, today);
}

// ── Words ───────────────────────────────────────────────────────────

const fmt = (n) => (n == null ? '?' : String(round1(n)));
const unitWord = (goal) => (goal.unit === '%' ? '%' : goal.unit === 'days/week' ? '' : ` ${goal.unit}`);

/** "Bench press 225 lbs" · "182 lbs" · "Body fat 16%" · "4 days a week" · "Hinge 8 sets a week". */
export function goalName(goal, { events = [] } = {}) {
    if (goal.name) return goal.name;
    const ev = goal.eventId ? events.find(e => e.id === goal.eventId) : null;
    const forEv = ev ? ` for ${ev.name}` : '';
    switch (goal.type) {
        case 'lift': return `${goal.key.exercise} ${fmt(goal.target)}${unitWord(goal)}`;
        case 'bodyweight': return `Body weight ${fmt(goal.target)}${unitWord(goal)}${forEv}`;
        case 'composition': return goal.metric === 'leanMass' ? `Lean mass ${fmt(goal.target)}${unitWord(goal)}${forEv}` : `Body fat ${fmt(goal.target)}%${forEv}`;
        case 'consistency': return `${fmt(goal.target)} days a week`;
        case 'balance': return `${PATTERN_LABELS[goal.key?.pattern] || goal.key?.pattern} ${fmt(goal.target)} sets a week`;
        default: return 'Goal';
    }
}

const STATUS_WORDS = {
    ahead: 'Ahead of pace.', 'on-track': 'On track.', behind: 'Behind.', met: 'Met.', missed: 'Missed.',
    'too-early': 'Too early to say.', 'no-date': '', 'no-data': '', paused: 'Paused.',
};

/** The pill label for a status. */
export const STATUS_LABELS = {
    ahead: 'Ahead', 'on-track': 'On track', behind: 'Behind', met: 'Met', missed: 'Missed',
    'too-early': 'Too early', 'no-date': 'No date', 'no-data': 'No data yet', paused: 'Paused',
};

function nowPhrase(goal, measured) {
    const u = unitWord(goal);
    switch (goal.type) {
        case 'lift': return `${goal.key.exercise}: estimated max ${fmt(measured.now)}${u}`;
        case 'bodyweight': return `Body weight ${fmt(measured.now)}${u} (7-day average)`;
        case 'composition': return `${goal.metric === 'leanMass' ? 'Lean mass' : 'Body fat'} ${fmt(measured.now)}${u} at the ${shortDate(measured.nowDate)} scan`;
        case 'consistency': return `${fmt(measured.now)} days a week over the last 4 weeks`;
        case 'balance': return `${PATTERN_LABELS[goal.key?.pattern] || goal.key?.pattern}: ${fmt(measured.now)} sets this week`;
        default: return '';
    }
}

function rateWords(goal, rate) {
    if (rate == null) return '';
    const u = goal.unit === '%' ? ' pts' : ` ${goal.unit}`;
    const a = Math.abs(rate);
    if (a < 0.05) return 'holding steady';
    const towards = goal.direction === 'down' ? rate < 0 : rate > 0;
    const verb = rate > 0 ? 'gaining' : 'losing';
    return towards ? `${verb} ${fmt(a)}${u}/week` : `moving the wrong way (${verb} ${fmt(a)}${u}/week)`;
}

function finish(goal, out, measured, today) {
    const u = unitWord(goal);
    const target = `${fmt(goal.target)}${u}`;
    let s;
    if (out.status === 'no-data') {
        const how = { lift: 'log a session of it', bodyweight: 'log a weigh-in', composition: 'add a DEXA scan', consistency: 'train', balance: 'train it' }[goal.type] || 'log data';
        s = `${goalName(goal)}: no data yet — ${how} and this fills in.`;
    } else if (goal.type === 'consistency' || goal.type === 'balance') {
        s = `${nowPhrase(goal, measured)} — goal ${target}. ${STATUS_WORDS[out.status]}`;
    } else {
        const head = nowPhrase(goal, measured);
        const by = goal.by ? `need ${target} by ${shortDate(goal.by)}` : `goal ${target}`;
        let tail;
        if (out.status === 'met') tail = 'Met.';
        else if (out.status === 'missed') tail = `Missed — ${shortDate(goal.by)} has passed.`;
        else if (out.status === 'paused') tail = 'Paused.';
        else if (out.status === 'too-early') tail = 'Too early to say — check back after a week.';
        else if (out.status === 'no-date') tail = out.actualRate != null ? `${rateWords(goal, out.actualRate)} since you set it.` : '';
        else {
            const need = out.requiredRate != null ? `, need ${fmt(Math.abs(out.requiredRate))}` : '';
            const word = out.status === 'behind' && out.slightly ? 'Slightly behind.' : STATUS_WORDS[out.status];
            tail = `${rateWords(goal, out.actualRate)}${need}. ${word}`;
        }
        // Between scans, the next scan is the measurement; bodyweight is the hint.
        if (goal.type === 'composition' && measured.nowDate && measured.nowDate < today && !['met', 'missed', 'paused'].includes(out.status)) {
            const w = measured.sinceScan;
            const hint = w == null ? '' : `; body weight is ${w === 0 ? 'unchanged' : `${w > 0 ? 'up' : 'down'} ${fmt(Math.abs(w))} ${measured.weightUnit}`} since then`;
            tail = `${tail ? `${tail} ` : ''}Next scan will tell${hint}.`;
        }
        s = `${head}, ${by}${tail ? ` — ${tail}` : '.'}`;
    }
    return { ...out, sentence: s.replace(/\s+/g, ' ').replace(/ \./g, '.').trim() };
}

// ── Lists + the coach's lines ───────────────────────────────────────

/** Weeks (rounded down) from today to an event. */
export function weeksUntil(date, today) {
    return Math.max(0, Math.floor(daysBetween(today, date) / 7));
}

/** Every active / paused goal with its measured status — what the page, the coach and the card all read. */
export function goalsWithStatus(goals = [], data = {}) {
    return (goals || [])
        .filter(g => g && g.status !== 'deleted')
        .map((g) => {
            if (g.status === 'met' || g.status === 'missed') {
                return { goal: g, measured: null, ...{ status: g.status, sentence: `${goalName(g, data)}: ${g.status === 'met' ? 'met' : 'missed'}.` } };
            }
            const measured = measureGoal(g, data);
            return { goal: g, measured, ...goalStatus(g, measured, data.today, { plates: data.plates }) };
        });
}

/**
 * The coach's `Goals:` / `Events:` lines. Facts to quote, the same rule as
 * the verdicts. '' when there is nothing to say. (The qualitative direction,
 * settings.coachGoal, is the profile's `Training for:` line.)
 */
export function formatGoalsContext({ goals = [], events = [], data = {} } = {}) {
    const lines = [];
    const rows = goalsWithStatus(goals.filter(g => g.status === 'active' || g.status === 'paused'), { ...data, events });
    if (rows.length) {
        lines.push('Goals (computed by the app — quote these sentences, don\'t re-derive them):');
        for (const r of rows) lines.push(`- [${r.goal.id || 'goal'}] ${r.sentence}`);
    }
    const upcoming = (events || []).filter(e => e?.date && (!data.today || e.date > data.today)).sort((a, b) => a.date.localeCompare(b.date));
    if (upcoming.length) {
        lines.push(`Events: ${upcoming.map(e => `[${e.id || 'event'}] ${e.name} on ${shortDate(e.date)} (${weeksUntil(e.date, data.today)} weeks)`).join(' · ')}`);
    }
    return lines.length ? `${lines.join('\n')}\n` : '';
}

