// Week targets (CP-3) — what a program week is allowed to SAY.
//
// Before this a weekTarget was { week, label, weightPct?, note? }: a
// percentage sign attached to a frozen recipe. A week can now also move set
// counts (setDelta), rep bands (repRange) and effort (rpeTarget), so a block
// has a shape — volume ramps, reps descend, RPE tightens, then a deload.
//
// Pure and import-free: the server validator (functions/coach-tools.js),
// the weekly review (functions/index.js), the coach context and the
// dashboard all read targets through these helpers.
//
// MIRRORED: functions/week-targets.js is generated by
//   node scripts/sync-mirror.mjs js/core/features/week-targets.js functions/week-targets.js
// (tests/unit/movement-patterns-mirror.test.js enforces parity).

const clip = (s, n) => String(s || '').trim().slice(0, n);

const SET_DELTA_MIN = -3;
const SET_DELTA_MAX = 3;

function intIn(v, min, max) {
    const n = parseInt(v, 10);
    if (isNaN(n) || n < min || n > max) return null;
    return n;
}

function repRangeOf(v) {
    if (!Array.isArray(v) || v.length !== 2) return null;
    const lo = intIn(v[0], 1, 50);
    const hi = intIn(v[1], 1, 50);
    if (lo == null || hi == null || lo > hi) return null;
    return [lo, hi];
}

function rpeOf(v) {
    const n = Number(v);
    if (!Number.isFinite(n) || n < 6 || n > 10) return null;
    return Math.round(n * 2) / 2;
}

/**
 * Validate + normalize one week target. Unknown fields are dropped; known
 * fields outside their range are dropped too (never silently clamped into
 * something the model didn't ask for).
 * @returns {{ok:true, target:object} | {ok:false, error:string}}
 */
export function normalizeWeekTarget(t, weeks) {
    const week = intIn(t?.week, 1, weeks);
    const label = clip(t?.label, 20);
    if (week == null || !label) return { ok: false, error: 'each weekTarget needs week (within program) + label' };
    const target = { week, label };
    if (typeof t.weightPct === 'number' && t.weightPct >= -90 && t.weightPct <= 100) target.weightPct = Math.round(t.weightPct);
    const setDelta = intIn(t.setDelta, SET_DELTA_MIN, SET_DELTA_MAX);
    if (setDelta != null && setDelta !== 0) target.setDelta = setDelta;
    const repRange = repRangeOf(t.repRange);
    if (repRange) target.repRange = repRange;
    const rpeTarget = rpeOf(t.rpeTarget);
    if (rpeTarget != null) target.rpeTarget = rpeTarget;
    if (t.note) target.note = clip(t.note, 80);
    return { ok: true, target };
}

/**
 * The session-changing effects of a target, normalized to nulls. A week
 * "changes the session" when any lever is non-zero — that is what gates the
 * auto-confirm pre-build and the propose-mode hero notice (Bug 8: they used
 * to look at weightPct alone, so a volume-only week was invisible).
 */
export function weekTargetEffects(target) {
    const weightPct = typeof target?.weightPct === 'number' && target.weightPct !== 0 ? target.weightPct : null;
    const setDelta = typeof target?.setDelta === 'number' && target.setDelta !== 0 ? target.setDelta : null;
    const repRange = repRangeOf(target?.repRange);
    const rpeTarget = rpeOf(target?.rpeTarget);
    return {
        weightPct, setDelta, repRange, rpeTarget,
        changesSession: weightPct != null || setDelta != null || repRange != null || rpeTarget != null,
    };
}

/** A deload is any week that pulls load OR volume back. */
export function isDeloadTarget(target) {
    const fx = weekTargetEffects(target);
    return (fx.weightPct != null && fx.weightPct < 0) || (fx.setDelta != null && fx.setDelta < 0);
}

/**
 * One human line for a target's levers: "-35% weight · -2 sets · 12–15 reps
 * · RPE 6". Empty string for a baseline week. Shared by the coach context,
 * the weekly review, the hero meta line and the program detail sheet so the
 * same week never reads differently in two places.
 */
export function describeWeekTarget(target) {
    const fx = weekTargetEffects(target);
    const parts = [];
    if (fx.weightPct != null) parts.push(`${fx.weightPct > 0 ? '+' : ''}${fx.weightPct}% weight`);
    if (fx.setDelta != null) parts.push(`${fx.setDelta > 0 ? '+' : ''}${fx.setDelta} set${Math.abs(fx.setDelta) === 1 ? '' : 's'}`);
    if (fx.repRange) parts.push(`${fx.repRange[0]}–${fx.repRange[1]} reps`);
    if (fx.rpeTarget != null) parts.push(`RPE ${fx.rpeTarget}`);
    return parts.join(' · ');
}
