// Progression (Phase 5.7.3) — deterministic double-progression, no API.
//
// The "coach" for the daily loop: given an exercise's recent completed
// sessions, decide today's target with a plain rule matrix (hit the rep
// target → add weight; below it → chase a rep; stuck → flag a stall). Pure,
// instant, offline. The model only ever sees the OUTPUT (stall flags), never
// runs this path.
//
// Extracted from active-workout-ui.js (was inline + mirror-tested); the render
// layer imports buildExerciseSessions/computeOverloadNudge from here now.
//
// MIRRORED: functions/progression.js is generated by
//   node scripts/sync-mirror.mjs js/core/features/progression.js functions/progression.js
// (tests/unit/movement-patterns-mirror.test.js enforces parity) — the
// server's get_verdicts tool and weekly review run THIS rule matrix, so the
// coach can't disagree with the set rows. Sibling imports only.

import { isRecoveryWorkout, recoveryNotes } from './session-intent.js';
import { convertToUnit } from './coach-outcomes.js';

const INCREMENT = { lbs: 5, kg: 2.5 };

/**
 * ui-helpers#convertWeight semantics (0 for missing, ≤0 or >1000 — the
 * corrupted-entry guard — else 1-decimal conversion) on the mirrored
 * converter, so this module needs nothing outside the mirrored set.
 */
function toDisplayUnit(weight, fromUnit, toUnit) {
    const w = Number(weight);
    if (!w || w <= 0 || w > 1000) return 0;
    return convertToUnit(w, fromUnit, toUnit);
}

/**
 * weight-calculations#plateRelativeWeight, inlined for the same reason: the
 * typed plate number on a base-weight machine, else the stored weight.
 * (progression.test.js pins the two to the same answers.)
 */
function plateRelative(set) {
    if (!set) return 0;
    if (typeof set._plateWeight === 'number' && set._equipBaseWeight > 0) return set._plateWeight;
    return set.weight || 0;
}

/**
 * The smallest REAL weight jump at this user's gym: plates load in pairs, so
 * it's 2× the smallest plate they own (from the plate-calculator settings) —
 * a gym with no 2.5 lb plates can't move a bar by 5. Floors at the classic
 * default so microplates don't shrink the standard progression jump. Pure:
 * callers pass the plate list (settings.plateLbs / settings.plateKg by unit).
 */
export function weightIncrement(unit, plates) {
    const fallback = INCREMENT[unit] || 5;
    if (!Array.isArray(plates) || plates.length === 0) return fallback;
    const smallest = Math.min(...plates.filter(p => typeof p === 'number' && p > 0));
    if (!Number.isFinite(smallest)) return fallback;
    return Math.max(fallback, smallest * 2);
}

/**
 * Scale a weight by `factor`, snapping the CHANGE to whole steps so the
 * result stays loadable. The starting weight was real (it was lifted), and
 * moving by multiples of the smallest jump keeps it real — rounding the
 * scaled value to a bare multiple of the step would not (a 45 lb bar with
 * 10 lb jumps lives on 95/105/115…, never 100). Pure.
 */
export function scaleLoadableWeight(weight, factor, step) {
    if (typeof weight !== 'number' || weight <= 0 || !step) return weight;
    const k = Math.round((weight * factor - weight) / step);
    const out = weight + k * step;
    return out > 0 ? Math.round(out * 10) / 10 : weight;
}

/**
 * Collapse a workout history into one entry per session for ONE exercise,
 * newest-first: { date, topWeight, topReps, maxReps, topRpe, rpeLogged } in
 * the display unit. Warmups excluded; a session with no working sets is
 * skipped. `topRpe` (AP-22) is the highest RPE logged on a working set at the
 * top weight — null when none was logged there.
 *
 * Deload/recovery sessions are excluded by default (AP-7): a −35% week is
 * not a strength signal. Left in, the week AFTER a deload read sessions[0]
 * as the light session and "earned" a bump off it (0.65·W + 5), and a deload
 * at full reps looked like a fresh plateau start.
 */
/** Machine name key: lowercase, separators folded — "Hammer-Strength  Row" = "hammer strength row". */
export function machineKey(name) {
    return String(name || '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
}

/**
 * THE same-machine rule (AP-3, now shared — AU-12): no machine asked for →
 * anything matches; a source that recorded no machine can't be called a
 * different one; otherwise stable id first, then the name key.
 * `src` = { equipment, equipmentId } (a last session or a logged exercise).
 */
export function sameMachine(equipName, equipId, src) {
    if (!equipName && !equipId) return true;
    if (!src) return false;
    if (equipId && src.equipmentId && equipId === src.equipmentId) return true;
    if (!src.equipment) return true;
    return !!equipName && machineKey(equipName) === machineKey(src.equipment);
}

/** Epley estimate; used only to compare a session against its own lift's recent best. */
const e1rmOf = (w, r) => (w > 0 && r > 0 ? w * (1 + Math.min(r, 12) / 30) : 0);
/** AU-10(a) — a noted session is "light" for a lift below this share of its 4-week best. */
export const LIGHT_NOTE_LOAD_SHARE = 0.85;

export function buildExerciseSessions(allWorkouts, exName, displayUnit, { excludeRecovery = true, machine = null } = {}) {
    if (!Array.isArray(allWorkouts) || !exName) return [];
    const sessions = [];
    const machinesSeen = new Set();
    for (const w of allWorkouts) {
        if (!w || !w.exercises || !w.date || !w.completedAt || w.cancelledAt) continue;
        if (excludeRecovery && isRecoveryWorkout(w)) continue;
        for (const [k, ex] of Object.entries(w.exercises)) {
            const name = w.exerciseNames?.[k] || ex?.name || ex?.machine;
            if (name !== exName) continue;
            // AU-12 — one machine's series: a High Row at 320 and a
            // Convergent at 90 are not one lift's history.
            if (machine && !sameMachine(machine.name, machine.id, ex)) continue;
            if (ex.equipment) machinesSeen.add(machineKey(ex.equipment));
            const working = (ex.sets || []).filter(s =>
                s && s.completed !== false && s.weight && (s.type || 'working') !== 'warmup');
            if (working.length === 0) break;
            // Plate-relative: on a base-weight machine the advisory has to
            // talk in the same number the set row asks for, or "bump to 385"
            // sits above a field the user types 270 into.
            const wOf = (s) => toDisplayUnit(
                plateRelative(s), s.originalUnit || 'lbs', displayUnit);
            let topWeight = 0;
            for (const s of working) {
                topWeight = Math.max(topWeight, wOf(s));
            }
            topWeight = Math.round(topWeight * 10) / 10;
            let topReps = 0, maxReps = 0, topRpe = null, rpeLogged = false;
            for (const s of working) {
                maxReps = Math.max(maxReps, s.reps || 0);
                const rpe = Number(s.rpe) > 0 ? Number(s.rpe) : null;
                if (rpe != null) rpeLogged = true;
                const w2 = Math.round(wOf(s) * 10) / 10;
                if (w2 === topWeight) {
                    topReps = Math.max(topReps, s.reps || 0);
                    if (rpe != null) topRpe = Math.max(topRpe ?? 0, rpe);
                }
            }
            sessions.push({ date: w.date, topWeight, topReps, maxReps, topRpe, rpeLogged, _noted: excludeRecovery && recoveryNotes(w).any });
            break; // one entry per workout
        }
    }
    sessions.sort((a, b) => b.date.localeCompare(a.date));
    // AU-10(a) — one "deload"/"light" note in the workout + this lift's top
    // set under 85% of its best over the previous 28 days = a light session
    // for this lift: left out, like a labelled deload. A note on a normal-load
    // day ("next week is deload") doesn't move anything.
    const skipped = [];
    const kept = sessions.filter((s, i) => {
        if (!s._noted) return true;
        const from = shiftDate(s.date, -28);
        let best = 0;
        for (const p of sessions.slice(i + 1)) {
            if (p.date < from) break;
            best = Math.max(best, e1rmOf(p.topWeight, p.topReps || p.maxReps));
        }
        const light = best > 0 && e1rmOf(s.topWeight, s.topReps || s.maxReps) < best * LIGHT_NOTE_LOAD_SHARE;
        if (light) skipped.push({ date: s.date, reason: 'notes + load' });
        return !light;
    });
    for (const s of kept) delete s._noted;
    if (skipped.length) Object.defineProperty(kept, 'lightSkipped', { value: skipped, enumerable: false });
    // Unfiltered and spread over 2+ machines: the caller should say so.
    if (!machine && machinesSeen.size > 1) Object.defineProperty(kept, 'mixedEquipment', { value: true, enumerable: false });
    return kept;
}

function shiftDate(date, days) {
    const d = new Date(`${date}T12:00:00`);
    d.setDate(d.getDate() + days);
    return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

/**
 * Today's deload target off the last BUILD session: weight scaled by the
 * intent's percentage (plate-loadable), reps at the bottom of the deload rep
 * band. Without a percentage (a volume-only deload, or a legacy labelled
 * session already scaled at start) the weight holds.
 */
export function deloadTarget(W, R, rt, intent, inc) {
    const pct = typeof intent?.weightPct === 'number' ? intent.weightPct : null;
    const weight = pct ? scaleLoadableWeight(W, 1 + pct / 100, inc) : W;
    const reps = intent?.repRange?.[0] ?? (rt || R || null);
    return { weight, reps };
}

/** The deload line for the last-session card. */
export function deloadNudgeText(W, R, rt, intent, displayUnit, inc) {
    const t = deloadTarget(W, R, rt, intent, inc);
    const repsStr = t.reps ? ` for ${t.reps}` : '';
    // A coach/user override says what it is ("Lighter week"); a program or
    // legacy deload keeps the classic wording.
    const head = intent?.source === 'manual' && intent.label && !/^deload$/i.test(intent.label) ? intent.label : 'Deload week';
    return t.weight !== W
        ? `${head} — ${t.weight} ${displayUnit}${repsStr}, two reps in the tank`
        : `${head} — hold ${W} ${displayUnit}, stop two reps short`;
}

/** Back-off factor for stall rung 2 — drop a step and rebuild. */
const BACK_OFF_FACTOR = 0.9;
/** Sessions per rung: 3 flat → chase reps, 6 → back off, 9 → rotate. */
const STALL_SESSIONS_PER_RUNG = 3;

/**
 * Stall ladder state (CP-2). A stall is a run of consecutive sessions
 * (newest first) at the same top weight with reps NOT climbing across the
 * run. Nothing is stored: the rung derives from history alone, so a
 * back-off session (different top weight) naturally resets the count.
 *
 * @returns {{run:number, repsClimbing:boolean, rung:0|1|2|3}}
 *   run   — sessions at the newest top weight (≥1)
 *   rung  — 0 = no stall · 1 chase-rep · 2 back-off · 3 rotate
 */
export function stallState(sessions) {
    if (!Array.isArray(sessions) || sessions.length === 0) return { run: 0, repsClimbing: false, rung: 0 };
    const W = sessions[0].topWeight;
    let run = 1;
    while (run < sessions.length && sessions[run].topWeight === W) run++;
    // "Climbing" compares the newest session against the start of the flat
    // run, so a slow grind (8 → 8 → 9 reps) still counts as progress.
    const repsClimbing = run >= 3 && (sessions[0].maxReps || 0) > (sessions[run - 1].maxReps || 0);
    const rung = run >= 3 && !repsClimbing ? Math.min(3, Math.floor(run / STALL_SESSIONS_PER_RUNG)) : 0;
    return { run, repsClimbing, rung };
}

/**
 * Fatigue signal (AP-22) — a LEADING indicator. Every other rule fires after
 * the weight or reps drop; effort climbing at the same load shows fatigue a
 * week earlier (three sessions at 185 at RPE 7.5 → 8.5 → 9 comes before
 * 185×6 turns into 185×3).
 *
 * Inert until RPE is logged: null when fewer than `minSessions` sessions
 * carry a top-set RPE — no RPE never reads as "fine" or as "fatigued".
 * Fatigued when either:
 *   - the last `minSessions` sessions sit at the same top load (within one
 *     `inc`), reps same-or-fewer end to end, and top-set RPE rose by at least
 *     `rpeRise`; or
 *   - the latest top set hit RPE ≥ 9.5 at a load previously done at ≤ 8.
 * Phase 2: progressionTarget acts on it — a fatigued stall skips to the
 * back-off rung early, and a fatigued lift is never bumped (hold instead).
 *
 * @param {Array} sessions - buildExerciseSessions output (newest first)
 * @returns {null|{fatigued:boolean, load:number, rpeTrend:number[],
 *   repsTrend:number[], reason:string}} trends oldest → newest
 */
export function fatigueState(sessions, { minSessions = 3, rpeRise = 1, inc = 5 } = {}) {
    if (!Array.isArray(sessions)) return null;
    const rated = sessions.filter(s => s?.topRpe != null);
    if (rated.length < minSessions) return null;
    const latest = sessions[0];
    const recent = sessions.slice(0, minSessions);
    const oldest = recent[recent.length - 1];
    const rpeTrend = recent.map(s => s.topRpe).reverse();
    const repsTrend = recent.map(s => s.topReps || s.maxReps || 0).reverse();
    const out = { fatigued: false, load: latest.topWeight, rpeTrend, repsTrend, reason: '' };

    if (recent.length === minSessions && recent.every(s => s.topRpe != null)) {
        const loads = recent.map(s => s.topWeight);
        const sameLoad = Math.max(...loads) - Math.min(...loads) <= inc;
        const repsHeld = (latest.topReps || 0) <= (oldest.topReps || 0);
        if (sameLoad && repsHeld && latest.topRpe - oldest.topRpe >= rpeRise) {
            out.fatigued = true;
            out.reason = `RPE ${rpeTrend.join('→')} at ${latest.topWeight} over ${minSessions} sessions`;
            return out;
        }
    }
    if (latest.topRpe != null && latest.topRpe >= 9.5) {
        const easier = sessions.slice(1).find(s =>
            s.topRpe != null && s.topRpe <= 8 && Math.abs(s.topWeight - latest.topWeight) < 0.05);
        if (easier) {
            out.fatigued = true;
            out.reason = `RPE ${latest.topRpe} at ${latest.topWeight}, was RPE ${easier.topRpe} on ${easier.date}`;
        }
    }
    return out;
}

/**
 * Smart progressive-overload coach for the last-session card. Reads the
 * multi-session history and applies double-progression logic:
 *   1. Plateau (3+ sessions at the same top weight) → the stall ladder:
 *      rung 1 chase a rep · rung 2 back off −10% · rung 3 rotate the movement.
 *      Reps climbing through the plateau → add weight instead.
 *   2. Hit the rep target at this weight → add weight.
 *   3. Just went up last session → consolidate before pushing again.
 *   4. Below the rep target → chase a rep first.
 *   5. Not enough signal → simple next-step suggestion.
 * Pure; returns the advisory string (or null).
 */
export function computeOverloadNudge(sessions, displayUnit, repTarget, increment, intent = null, today = null) {
    if (!Array.isArray(sessions) || sessions.length === 0) return null;
    // AU-11 — the card says what progressionTarget decided.
    if (intent?.mode !== 'deload') {
        const t = progressionTarget(sessions, displayUnit, repTarget, increment, intent, today);
        if (t?.action === 'reacquaint') {
            return `Last done ${t.staleDays} days ago — start at ${t.weight} ${displayUnit} and feel it out`;
        }
        if (t?.warning === 'light-session' && t.fromSession) {
            const k = sessions.findIndex(s => s.date === t.fromSession);
            const rest = computeOverloadNudge(sessions.slice(k), displayUnit, repTarget, increment, intent, null);
            return rest ? `${rest} (last session looked light — going off ${t.fromSession})` : null;
        }
    }
    const cur = sessions[0];
    const W = cur.topWeight;
    if (!W) return null;
    const inc = increment || INCREMENT[displayUnit] || 5;
    const next = Math.round((W + inc) * 10) / 10;
    const rt = repTarget && repTarget > 0 ? repTarget : null;
    const R = cur.topReps || cur.maxReps || 0;

    // 0) Deload session — never "go heavier", whatever history says.
    if (intent?.mode === 'deload') return deloadNudgeText(W, R, rt, intent, displayUnit, inc);

    // 1) Plateau — same top weight three sessions running.
    const stall = stallState(sessions);
    // AP-22 phase 2 — same calls as progressionTarget, so card and rows agree.
    const fatigue = fatigueState(sessions, { inc });
    const fatigued = !!fatigue?.fatigued;
    if (fatigued && stall.rung === 1) {
        const back = scaleLoadableWeight(W, BACK_OFF_FACTOR, inc);
        return `Effort is climbing at ${W} ${displayUnit} (${fatigue.reason}) — drop to ${back} for two sessions, then back at it`;
    }
    if (fatigued && stall.rung === 0 && ((rt && R >= rt) || (stall.run >= 3 && stall.repsClimbing))) {
        return `${R} reps at ${W} ${displayUnit}, but effort is climbing (${fatigue.reason}) — hold ${W} before the next jump`;
    }
    if (stall.run >= 3) {
        if (stall.repsClimbing) return `${stall.run} sessions at ${W} ${displayUnit} — reps are climbing, go ${next} next`;
        // Never offer MORE load at a detected stall (the old string did).
        if (stall.rung === 1) return `${ordinal(stall.run)} session at ${W} ${displayUnit} — hold it and chase ${R + 1}`;
        if (stall.rung === 2) {
            const back = scaleLoadableWeight(W, BACK_OFF_FACTOR, inc);
            return `${stall.run} sessions at ${W} ${displayUnit} — drop to ${back} for two sessions, then back at it`;
        }
        return `${W} ${displayUnit} has had its run (${stall.run} sessions flat) — swap in a similar movement this block`;
    }
    // 2) Double progression — hit the rep target, time to add weight.
    if (rt && R >= rt) {
        return `${R} reps at ${W} ${displayUnit} — bump to ${next}`;
    }
    // 3) Went up last session — lock it in before the next jump.
    if (sessions.length >= 2 && W > sessions[1].topWeight) {
        return `Up from ${sessions[1].topWeight} — own ${W} ${displayUnit} for ${rt || R || 'your'} reps`;
    }
    // 4) Below the rep target — chase a rep first.
    if (rt && R > 0 && R < rt) {
        return `Add a rep — aim ${R + 1}×${W} ${displayUnit} toward ${rt}`;
    }
    // 5) Fallback — simple progressive step.
    return `Beat it — try ${next} ${displayUnit}`;
}

function ordinal(n) {
    const s = ['th', 'st', 'nd', 'rd'];
    const v = n % 100;
    return `${n}${s[(v - 20) % 10] || s[v] || s[0]}`;
}

/**
 * Structured recommendation for the same rule matrix (5.7.3): today's target
 * weight/reps, whether it's a bump (↑ marker), and a stall flag the coach
 * context can read. Kept separate from computeOverloadNudge so the advisory
 * string and the machine-readable target never drift.
 *
 * Stall rungs (CP-2) all carry `stalled: true` plus `rung` and `stallRun`:
 *   rung 1 `chase-rep` — hold W, reps R+1 (advice only; nothing is seeded)
 *   rung 2 `back-off`  — weight = plate-rounded 90% of W, `backOff: true`
 *                        (the set rows seed the reduced load)
 *   rung 3 `rotate`    — hold W, `rotate: true` (hand-off to the variety
 *                        engine; until then a swap suggestion)
 *
 * A deload intent (AP-7) short-circuits to `action:'deload', deload:true`.
 *
 * Fatigue (AP-22 phase 2, `fatigueState`): a fatigued rung-1 stall skips to
 * the back-off rung (`rung:2, early:true`); a fatigued lift that would bump
 * holds instead (`action:'consolidate'`). Every target for a fatigued lift
 * carries `fatigued:true, fatigueReason`.
 *
 * @returns {{weight:number, reps:number|null, bumped:boolean, stalled:boolean,
 *            action:'bump'|'consolidate'|'chase-rep'|'back-off'|'rotate'|'start'|'deload',
 *            rung?:number, stallRun?:number, backOff?:boolean, rotate?:boolean}|null}
 */
/** Every action progressionTarget can return — consumers must handle each (AU-11; tested). */
export const PROGRESSION_ACTIONS = ['bump', 'consolidate', 'chase-rep', 'back-off', 'rotate', 'start', 'deload', 'reacquaint'];
/** AU-11 — a verdict off a session older than this restarts at the last weight. */
export const STALE_SESSION_DAYS = 42;
/** AU-11 — a target implying less than this share of the 4-week best e1RM is suspect. */
export const LIGHT_TARGET_SHARE = 0.8;

function daysBetween(a, b) {
    return Math.round((Date.parse(`${b}T12:00:00`) - Date.parse(`${a}T12:00:00`)) / 86400000);
}

/** Best top-set e1RM over the 28 days ending at the newest session. */
function bestE1rm4wk(sessions) {
    const from = shiftDate(sessions[0].date, -28);
    let best = 0;
    for (const s of sessions) {
        if (s.date < from) break;
        best = Math.max(best, e1rmOf(s.topWeight, s.topReps || s.maxReps));
    }
    return best;
}

/**
 * Today's target (see targetFromSessions for the rule matrix), plus two
 * cross-checks the engine runs on its own numbers (AU-11):
 *   - **Stale** (`today` given, newest session > 6 weeks old): `reacquaint` —
 *     start at the last weight, no bump. Inert when `today` is null, so
 *     callers migrate one at a time.
 *   - **Light** (not a deload): a target whose implied e1RM is < 80 % of the
 *     lift's 4-week best was computed off a light session the rules weren't
 *     told about — recompute from the newest session within 85–115 % of that
 *     best and flag `warning:'light-session'`, `fromSession`.
 */
export function progressionTarget(sessions, displayUnit, repTarget, increment, intent = null, today = null) {
    if (!Array.isArray(sessions) || sessions.length === 0) return null;
    const cur = sessions[0];
    if (today && intent?.mode !== 'deload' && cur.topWeight) {
        const staleDays = daysBetween(cur.date, today);
        if (staleDays > STALE_SESSION_DAYS) {
            const rt = repTarget && repTarget > 0 ? repTarget : null;
            return {
                weight: cur.topWeight, reps: rt || cur.topReps || cur.maxReps || null,
                bumped: false, stalled: false, action: 'reacquaint', reacquaint: true, staleDays,
            };
        }
    }
    const t = targetFromSessions(sessions, displayUnit, repTarget, increment, intent);
    if (!t || intent?.mode === 'deload') return t;
    const best = bestE1rm4wk(sessions);
    const implied = e1rmOf(t.weight, t.reps || cur.topReps || cur.maxReps);
    if (!(best > 0) || implied >= best * LIGHT_TARGET_SHARE) return t;
    const k = sessions.findIndex((s, i) => {
        if (i === 0) return false;
        const e = e1rmOf(s.topWeight, s.topReps || s.maxReps);
        return e >= best * 0.85 && e <= best * 1.15;
    });
    if (k < 1) return { ...t, warning: 'light-session' };
    const alt = targetFromSessions(sessions.slice(k), displayUnit, repTarget, increment, intent);
    return alt ? { ...alt, warning: 'light-session', fromSession: sessions[k].date } : { ...t, warning: 'light-session' };
}

/** The rule matrix proper (no cross-checks) — progressionTarget wraps it. */
function targetFromSessions(sessions, displayUnit, repTarget, increment, intent = null) {
    if (!Array.isArray(sessions) || sessions.length === 0) return null;
    const cur = sessions[0];
    const W = cur.topWeight;
    if (!W) return null;
    const inc = increment || INCREMENT[displayUnit] || 5;
    const next = Math.round((W + inc) * 10) / 10;
    const rt = repTarget && repTarget > 0 ? repTarget : null;
    const R = cur.topReps || cur.maxReps || 0;

    // Deload session: the stall ladder doesn't run (a planned light week is
    // not a plateau) and nothing is a bump.
    if (intent?.mode === 'deload') {
        const t = deloadTarget(W, R, rt, intent, inc);
        return { weight: t.weight, reps: t.reps, bumped: false, stalled: false, action: 'deload', deload: true };
    }

    const stall = stallState(sessions);
    const repsClimbing = stall.run >= 3 && stall.repsClimbing;
    const fatigue = fatigueState(sessions, { inc });
    const tag = fatigue?.fatigued ? { fatigued: true, fatigueReason: fatigue.reason } : {};

    // Effort climbing at a stalled load: the back-off comes a rung early.
    if (tag.fatigued && stall.rung === 1) {
        return {
            bumped: false, stalled: true, rung: 2, stallRun: stall.run, early: true,
            weight: scaleLoadableWeight(W, BACK_OFF_FACTOR, inc), reps: rt || R || null,
            action: 'back-off', backOff: true, ...tag,
        };
    }
    // Earned a bump on reps, but the effort says not yet — hold.
    if (tag.fatigued && stall.rung === 0 && ((rt && R >= rt) || repsClimbing)) {
        return { weight: W, reps: rt || R || null, bumped: false, stalled: false, action: 'consolidate', ...tag };
    }
    const result = progressionTargetCore(sessions, { W, R, rt, inc, next, stall, repsClimbing });
    return tag.fatigued ? { ...result, ...tag } : result;
}

function progressionTargetCore(sessions, { W, R, rt, inc, next, stall, repsClimbing }) {
    // Stall: three+ sessions at the same weight with reps NOT climbing — a
    // true plateau, answered by the rung rather than a terminal flag.
    if (stall.rung >= 1) {
        const base = { bumped: false, stalled: true, rung: stall.rung, stallRun: stall.run };
        if (stall.rung === 1) return { ...base, weight: W, reps: R + 1, action: 'chase-rep' };
        if (stall.rung === 2) {
            return { ...base, weight: scaleLoadableWeight(W, BACK_OFF_FACTOR, inc), reps: rt || R || null, action: 'back-off', backOff: true };
        }
        return { ...base, weight: W, reps: rt || R || null, action: 'rotate', rotate: true };
    }
    // Earned the bump: hit the rep target (or reps climbed through a plateau).
    if ((rt && R >= rt) || repsClimbing) {
        return { weight: next, reps: rt || R || null, bumped: true, stalled: false, action: 'bump' };
    }
    // Went up last session — hold and own it.
    if (sessions.length >= 2 && W > sessions[1].topWeight) {
        return { weight: W, reps: rt || R || null, bumped: false, stalled: false, action: 'consolidate' };
    }
    // Below the rep target — same weight, chase a rep.
    if (rt && R > 0 && R < rt) {
        return { weight: W, reps: R + 1, bumped: false, stalled: false, action: 'chase-rep' };
    }
    // Not enough signal — hold last weight, no marker.
    return { weight: W, reps: rt || R || null, bumped: false, stalled: false, action: 'start' };
}
