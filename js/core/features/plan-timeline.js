// Plan timeline (TP-3) — one continuous plan, not a stack of blocks.
//
// The user never sees a "block" (D1). The engine still runs in waves
// (programs: build weeks then a lighter one), and this module stitches them
// into one timeline: past and current weeks from real programs and real
// workouts (block-view.js cells, reused), planned weeks of the active wave
// with their targets, and projected weeks to the horizon from the plan's
// cadence — session names and week kinds, no numbers (loads that far out
// would be invented). Events reshape the projection: peak weeks up to the
// event, a lighter week just before them, the pattern restarting after.
//
// Pure. Imports only mirrored siblings.
//
// MIRRORED: functions/plan-timeline.js is generated by
//   node scripts/sync-mirror.mjs js/core/features/plan-timeline.js functions/plan-timeline.js
// (tests/unit/movement-patterns-mirror.test.js enforces parity).

import { buildBlockModel, addDays } from './block-view.js';
import { weekKindOf } from './plain-language.js';
import { isManualDeloadActive } from './session-intent.js';
import { goalsWithStatus, goalName, shortDate, STATUS_LABELS } from './goal-progress.js';

export const DAY_KEYS = ['mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun'];
const DAY_LABELS = { mon: 'Mon', tue: 'Tue', wed: 'Wed', thu: 'Thu', fri: 'Fri', sat: 'Sat', sun: 'Sun' };
export const DEFAULT_CADENCE = { buildWeeks: 3, lighterWeek: true };
export const DEFAULT_HORIZON_WEEKS = 12;
export const MAX_PAST_WEEKS = 8;
export const KIND_LABELS = { build: 'Build week', push: 'Push week', peak: 'Peak week', lighter: 'Lighter week' };
const NUMBER_WORDS = ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight'];

const dayIdx = (d) => (new Date(`${d}T12:00:00`).getDay() + 6) % 7;
export const mondayOf = (d) => addDays(d, -dayIdx(d));
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const monthOf = (d) => MONTHS[Number(d.slice(5, 7)) - 1];

export function cadenceOf(plan) {
    const c = plan?.cadence || {};
    const buildWeeks = Number.isInteger(c.buildWeeks) && c.buildWeeks >= 1 && c.buildWeeks <= 8 ? c.buildWeeks : DEFAULT_CADENCE.buildWeeks;
    return { buildWeeks, lighterWeek: c.lighterWeek !== false };
}

/** "three build weeks then a lighter one" */
export function describeCadence(cadence) {
    const c = cadence || DEFAULT_CADENCE;
    const n = NUMBER_WORDS[c.buildWeeks] || String(c.buildWeeks);
    return c.lighterWeek ? `${n} build week${c.buildWeeks === 1 ? '' : 's'} then a lighter one` : 'build weeks only, no lighter week';
}

/** The kind of the i-th week (0-based) of a wave: build… (last one push), then lighter. */
export function cadenceKind(i, cadence) {
    const c = cadence || DEFAULT_CADENCE;
    const len = c.buildWeeks + (c.lighterWeek ? 1 : 0);
    const pos = ((i % len) + len) % len;
    if (pos >= c.buildWeeks) return 'lighter';
    return c.buildWeeks >= 2 && pos === c.buildWeeks - 1 ? 'push' : 'build';
}

/**
 * Week kinds for `count` weeks starting `start`, from the cadence, with each
 * upcoming event's window applied: the `peakWeeks` weeks before the event
 * and its own week are peak, the week before them lighter (unless
 * `lighterBefore` is off), and the cadence restarts after the event week.
 * @param {{offset?: number}} [opts] - where in the cadence `start` falls (0 = a wave's first week)
 * @returns {Array<{weekStart: string, kind: string, event: object|null}>}
 */
export function projectKinds(start, count, cadence, events = [], { offset = 0 } = {}) {
    const windows = (events || []).filter(e => e?.date && e.kind !== 'travel').map((e) => {
        const eventMonday = mondayOf(e.date);
        const peakWeeks = Number.isInteger(e.peakWeeks) ? e.peakWeeks : 2;
        return {
            e, eventMonday,
            peakFrom: addDays(eventMonday, -7 * peakWeeks),
            lighter: e.lighterBefore === false ? null : addDays(eventMonday, -7 * (peakWeeks + 1)),
        };
    });
    const out = [];
    let pos = offset;
    for (let k = 0; k < count; k++) {
        const ws = addDays(start, 7 * k);
        const we = addDays(ws, 6);
        // The event's window wins over the cadence. Match by the week's Monday
        // so a wave starting mid-week still lands on the right window.
        const wm = mondayOf(ws);
        const inPeak = windows.find(w => wm >= w.peakFrom && wm <= w.eventMonday);
        const isLighterBefore = windows.find(w => w.lighter === wm);
        if (inPeak) {
            out.push({ weekStart: ws, kind: 'peak', event: inPeak.e });
            if (inPeak.e.date <= we || wm === inPeak.eventMonday) pos = 0; // restart after the event
            continue;
        }
        if (isLighterBefore) {
            out.push({ weekStart: ws, kind: 'lighter', event: isLighterBefore.e });
            continue;
        }
        out.push({ weekStart: ws, kind: cadenceKind(pos, cadence), event: null });
        pos++;
    }
    return out;
}

function programEnd(p) {
    return addDays(p.startDate, Math.max(1, Number(p.weeks) || 1) * 7 - 1);
}

/** Programs that actually ran, in order, each cut off where the next one started. */
export function programRuns(programs = []) {
    const list = (programs || []).filter(p => p?.startDate && Number(p.weeks) > 0)
        .sort((a, b) => a.startDate.localeCompare(b.startDate) || String(a.createdAt || '').localeCompare(String(b.createdAt || '')));
    return list.map((p, i) => {
        const next = list[i + 1];
        const end = programEnd(p);
        return { program: p, start: p.startDate, end: next && next.startDate <= end ? addDays(next.startDate, -1) : end };
    }).filter(r => r.end >= r.start);
}

function projectedCells(weekStart, weekPlan, templates, workouts, today) {
    const byId = new Map((templates || []).map(t => [t.id, t]));
    const days = weekPlan?.days || {};
    const startIdx = dayIdx(weekStart);
    return DAY_KEYS.filter(d => days[d] && days[d] !== 'rest').map((d) => {
        const date = addDays(weekStart, (DAY_KEYS.indexOf(d) - startIdx + 7) % 7);
        const name = byId.get(days[d])?.name || days[d];
        const done = (workouts || []).find(w => w?.date === date && w.completedAt && !w.cancelledAt);
        let status = 'projected';
        if (date <= today) status = done ? 'done' : date === today ? 'today' : 'missed';
        return { day: d, dayLabel: DAY_LABELS[d], date, templateId: days[d], name, status, primary: null, workoutId: done?.id || null, doneOn: done?.date || null };
    }).sort((a, b) => a.date.localeCompare(b.date));
}

/**
 * @param {object} args
 * @param {object|null} args.plan - users/{uid}/plan/current
 * @param {object|null} args.weekPlan - preferences/weekPlan (the split's one home)
 * @param {Array} args.programs - every program doc (past and active)
 * @returns {{weeks: Array, goalsStrip: Array, header: object, horizonEnd: string, activeProgram: object|null}}
 */
export function buildPlanTimeline({
    plan = null, weekPlan = null, programs = [], templates = [], workouts = [], goals = [], events = [],
    measurements = [], dexa = [], override = null, today, unit = 'lbs', plates = null,
} = {}) {
    const cadence = cadenceOf(plan);
    const horizonWeeks = Number.isInteger(plan?.horizonWeeks) && plan.horizonWeeks >= 4 && plan.horizonWeeks <= 26 ? plan.horizonWeeks : DEFAULT_HORIZON_WEEKS;
    const horizonEnd = addDays(mondayOf(today), horizonWeeks * 7 - 1);
    const pastFloor = addDays(mondayOf(today), -7 * MAX_PAST_WEEKS);
    const runs = programRuns(programs);
    const weeks = [];

    for (const run of runs) {
        if (run.end < pastFloor) continue;
        const model = buildBlockModel({ program: run.program, templates, workouts, today, unit, plates, override });
        if (!model) continue;
        for (const w of model.weeks) {
            if (w.start > run.end || w.end < pastFloor) continue;
            const target = (run.program.weekTargets || []).find(t => t.week === w.week) || null;
            const kind = weekKindOf(target);
            const state = w.end < today ? 'past' : w.start <= today ? 'current' : 'planned';
            weeks.push({
                weekStart: w.start, weekEnd: w.end, kind, label: KIND_LABELS[kind], levers: w.levers,
                state, programId: run.program.id || null, waveWeek: w.week, waveWeeks: model.header.weeks,
                days: w.cells, override: w.override, markers: [],
            });
        }
    }

    // Projection: from the day after the last wave (or this Monday) to the horizon.
    const lastEnd = weeks.length ? weeks[weeks.length - 1].weekEnd : null;
    let cursor = lastEnd ? addDays(lastEnd, 1) : mondayOf(today);
    if (cursor < mondayOf(today) && !weeks.some(w => w.state === 'current')) {
        // The last wave ended weeks ago: the projection picks up this week.
        cursor = mondayOf(today);
    }
    if (plan?.paused !== true && cursor <= horizonEnd) {
        const days = Math.round((new Date(`${horizonEnd}T12:00:00`) - new Date(`${cursor}T12:00:00`)) / 86400000) + 1; // round: DST
        const count = Math.ceil(Math.max(0, days) / 7);
        const futureEvents = (events || []).filter(e => e?.date && e.date >= cursor);
        for (const p of projectKinds(cursor, count, cadence, futureEvents)) {
            const we = addDays(p.weekStart, 6);
            const state = we < today ? 'past' : p.weekStart <= today ? 'current' : 'projected';
            const ovActive = override && [0, 1, 2, 3, 4, 5, 6].some(i => isManualDeloadActive(override, addDays(p.weekStart, i)));
            weeks.push({
                weekStart: p.weekStart, weekEnd: we, kind: ovActive ? 'lighter' : p.kind, label: KIND_LABELS[ovActive ? 'lighter' : p.kind],
                levers: '', state, programId: null, waveWeek: null, waveWeeks: null,
                days: projectedCells(p.weekStart, weekPlan, templates, workouts, today),
                override: ovActive ? { label: override.label || 'Lighter week', reason: override.reason || null } : null,
                markers: [], projected: true,
            });
        }
    }

    // Markers: goal dates and event dates on their weeks.
    const rows = goalsWithStatus((goals || []).filter(g => g.status === 'active' || g.status === 'paused'), {
        workouts, templates, measurements, dexa, today, plates, events,
    });
    const weekOf = (date) => weeks.find(w => date >= w.weekStart && date <= w.weekEnd);
    for (const r of rows) {
        if (!r.goal.by) continue;
        const w = weekOf(r.goal.by);
        if (w) w.markers.push({ type: 'goal', label: `${goalName(r.goal, { events })} by ${shortDate(r.goal.by)}`, status: r.status });
    }
    for (const e of events || []) {
        const w = e?.date && weekOf(e.date);
        if (!w) continue;
        // TP-7 c — a trip shows its dates ("Bellagio · Nov 1–2").
        const range = e.kind === 'travel' && e.endDate && e.endDate !== e.date ? `${shortDate(e.date)}–${shortDate(e.endDate)}` : shortDate(e.date);
        w.markers.push({ type: e.kind === 'travel' ? 'travel' : 'event', label: `${e.name} · ${range}` });
    }

    const current = weeks.find(w => w.state === 'current') || null;
    // "Build week 2": how far into the current run of this kind, never "week 2 of 4".
    let runIndex = 0;
    if (current) {
        const i = weeks.indexOf(current);
        runIndex = 1;
        // A new wave starts its own count (TP-6 h: five build weeks of the old
        // wave + week 1 of the new one read "Build week 6").
        for (let k = i - 1; k >= 0 && weeks[k].kind === current.kind && weeks[k].programId === current.programId; k--) runIndex++;
    }
    const nextLighter = weeks.find(w => w.weekStart > today && w.kind === 'lighter') || null;
    const nextEvent = (events || []).filter(e => e?.date && e.date >= today).sort((a, b) => a.date.localeCompare(b.date))[0] || null;
    const active = runs.find(r => r.start <= today && r.end >= today)?.program || null;
    // TP-6 a/c — when the next weeks get set up: the day after the last wave
    // (or next Monday), rolled the Sunday before. Same rule as rollWindow.
    const lastRun = runs.length ? runs[runs.length - 1] : null;
    const chain = lastRun ? addDays(lastRun.end, 1) : null;
    const nextWeeksFrom = plan && plan.paused !== true ? (chain && chain >= today ? chain : addDays(mondayOf(today), 7)) : null;
    return {
        weeks,
        horizonEnd,
        activeProgram: active,
        goalsStrip: rows.map(r => ({ id: r.goal.id || null, name: goalName(r.goal, { events }), status: r.status, statusLabel: STATUS_LABELS[r.status] || '' })),
        header: {
            name: plan?.name || 'My plan',
            cadence, cadenceText: describeCadence(cadence),
            paused: plan?.paused === true,
            thisWeek: current ? `${current.label}${current.kind === 'build' || current.kind === 'push' ? ` ${runIndex}` : ''}` : null,
            thisWeekKind: current?.kind || null,
            nextLighter: nextLighter ? nextLighter.weekStart : null,
            nextWeeksFrom,
            nextRoll: nextWeeksFrom ? addDays(nextWeeksFrom, -1) : null,
            nextEvent: nextEvent ? { name: nextEvent.name, date: nextEvent.date, weeks: Math.max(0, Math.floor(Math.round((new Date(`${nextEvent.date}T12:00:00`) - new Date(`${today}T12:00:00`)) / 86400000) / 7)) } : null,
            through: monthOf(horizonEnd),
        },
    };
}

/**
 * The coach's `Your plan:` line (A2) — the plan in the user's words; the
 * wave/program is never named. '' without a plan or a split.
 */
export function formatPlanContext({ plan = null, weekPlan = null, templates = [], timeline = null, goalsRows = [], events = [], today } = {}) {
    const days = weekPlan?.days || {};
    const byId = new Map((templates || []).map(t => [t.id, t]));
    const split = DAY_KEYS.filter(d => days[d] && days[d] !== 'rest').map(d => `${DAY_LABELS[d]} ${byId.get(days[d])?.name || days[d]}`);
    if (!plan && !split.length) return '';
    const parts = [];
    if (split.length) parts.push(`${split.length} day${split.length === 1 ? '' : 's'} (${split.join(' · ')})`);
    if (plan) {
        parts.push(describeCadence(cadenceOf(plan)));
        if (plan.paused) parts.push('paused — it does not continue on its own');
        else if (timeline) parts.push(`through ${timeline.header.through}`);
        if (plan.rotationPolicy === 'auto') parts.push('accessory swaps happen automatically when the next weeks are set up');
        if (plan.sessionMinutes) parts.push(`${plan.sessionMinutes} min sessions`);
        const fixed = Object.entries(plan.fixed || {}).filter(([d, v]) => DAY_LABELS[d] && v?.mustInclude?.length);
        if (fixed.length) parts.push(`fixed: ${fixed.map(([d, v]) => `${DAY_LABELS[d]} ${v.mustInclude.join(' + ')}`).join(', ')}`);
    }
    if (timeline?.header.thisWeek) parts.push(`this week: ${timeline.header.thisWeek}`);
    if (timeline?.header.nextLighter && timeline.header.nextLighter > today) parts.push(`lighter week starts ${shortDate(timeline.header.nextLighter)}`);
    const behind = (goalsRows || []).filter(r => r.status === 'behind').length;
    if ((goalsRows || []).length) parts.push(`${goalsRows.length} goal${goalsRows.length === 1 ? '' : 's'}${behind ? ` (${behind} behind)` : ''}`);
    const upcoming = (events || []).filter(e => e?.date && e.date > today);
    if (upcoming.length) parts.push(`${upcoming.length} event${upcoming.length === 1 ? '' : 's'}`);
    return `Your plan: ${parts.join(' · ')}\n`;
}

/**
 * TP-6 c — the plan in one line for Home, from the SAME header the Plan page
 * renders (so the two can't disagree): "My plan · Build week 3" over
 * "lighter week starts Nov 2 · Trip in 5 weeks · 2 swaps waiting".
 * @param {object} header - buildPlanTimeline().header
 * @param {{hasPlan?: boolean, waiting?: number}} [opts]
 * @returns {{title: string, meta: string}}
 */
export function planSummaryLine(header, { hasPlan = true, waiting = 0 } = {}) {
    const h = header || {};
    const meta = [
        h.paused ? 'paused' : null,
        h.nextLighter ? `lighter week starts ${shortDate(h.nextLighter)}` : null,
        h.nextEvent ? `${h.nextEvent.name} in ${h.nextEvent.weeks} week${h.nextEvent.weeks === 1 ? '' : 's'}` : null,
        waiting ? `${waiting} swap${waiting === 1 ? '' : 's'} waiting` : null,
        hasPlan && !h.paused && !h.nextLighter && h.nextRoll ? `next weeks set up ${shortDate(h.nextRoll)}` : null,
        !hasPlan ? 'turn it on to keep it going' : null,
    ].filter(Boolean);
    return { title: [h.name, h.thisWeek].filter(Boolean).join(' · '), meta: meta.join(' · ') };
}
