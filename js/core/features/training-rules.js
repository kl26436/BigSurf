// Training rules (AP-16) — the pure, threshold-driven half of the insights
// engine: body-part mapping, weekly volume vs MEV/MRV, tonnage, ISO weeks and
// the deload check. Moved out of training-insights.js (which reads AppState
// and Config) so the server can run the SAME rules for the coach's
// `get_verdicts` tool and the weekly review — before this the server had no
// deload check and no volume math at all, and the model re-derived both from
// raw history.
//
// Thresholds are injected (defaults below are the app's single source:
// config.js spreads RULE_THRESHOLDS into Config).
//
// MIRRORED: functions/training-rules.js is generated by
//   node scripts/sync-mirror.mjs js/core/features/training-rules.js functions/training-rules.js
// (tests/unit/movement-patterns-mirror.test.js enforces parity).

import { isRecoveryWorkout } from './session-intent.js';
import { buildExerciseSessions, fatigueState } from './progression.js';

export const RULE_THRESHOLDS = {
    VOLUME_MEV: 8,              // Minimum Effective Volume (sets/muscle/week)
    VOLUME_MRV: 22,             // Maximum Recoverable Volume (sets/muscle/week)
    PLATEAU_MIN_SESSIONS: 3,    // Sessions with no progression to flag plateau
    DELOAD_DAYS_PER_WEEK: 5,    // Days/week threshold for "hard week"
    DELOAD_CONSECUTIVE_WEEKS: 4, // Consecutive hard weeks before suggesting deload
    DELOAD_TONNAGE_DROP: 0.25,  // A full-frequency week this far below the trailing 3-week tonnage mean is a recovery week
    PATTERN_TARGET_SETS: 8,     // Scoreboard: weekly sets per movement pattern (squat, hinge, push/pull ×2) below this read "under" — separate knob from per-muscle MEV
    READINESS_WINDOW_DAYS: 10,  // AP-22: readiness check-ins looked at
    READINESS_LOW_COUNT: 3,     // AP-22: this many ≤2/5 check-ins in the window = readiness low
};

/**
 * Readiness (AP-22) — the 1–5 "how do you feel" check-in, counted. Low
 * scores are a leading fatigue signal the rules never read before.
 * @returns {{low:number, of:number, avg:number|null, readinessLow:boolean}}
 */
export function readinessState(workouts, { today = null, days = RULE_THRESHOLDS.READINESS_WINDOW_DAYS, lowCount = RULE_THRESHOLDS.READINESS_LOW_COUNT } = {}) {
    const done = (workouts || []).filter(w => w?.date && w.completedAt && !w.cancelledAt);
    const end = today || done.reduce((m, w) => (w.date > m ? w.date : m), '');
    if (!end) return { low: 0, of: 0, avg: null, readinessLow: false };
    const from = shiftDay(end, -(days - 1));
    const scores = done
        .filter(w => w.date >= from && w.date <= end && Number(w.readiness?.score) > 0)
        .map(w => Number(w.readiness.score));
    const low = scores.filter(x => x <= 2).length;
    const avg = scores.length ? Math.round((scores.reduce((a, b) => a + b, 0) / scores.length) * 10) / 10 : null;
    return { low, of: scores.length, avg, readinessLow: low >= lowCount };
}

/**
 * Exercises showing the AP-22 fatigue signal, trained in the last 3 weeks.
 * @returns {Array<{exercise:string, reason:string, load:number}>}
 */
export function fatigueSignals(workouts, { today = null, unit = 'lbs', inc = 5, minSessions = RULE_THRESHOLDS.PLATEAU_MIN_SESSIONS } = {}) {
    const done = (workouts || []).filter(w => w?.date && w.completedAt && !w.cancelledAt);
    const end = today || done.reduce((m, w) => (w.date > m ? w.date : m), '');
    if (!end) return [];
    const from = shiftDay(end, -20);
    const names = new Set();
    for (const w of done) {
        if (w.date < from || w.date > end) continue;
        for (const ex of withResolvedNames(w)) {
            if (ex.name && (ex.sets || []).some(st => Number(st?.rpe) > 0)) names.add(ex.name);
        }
    }
    const out = [];
    for (const name of names) {
        const f = fatigueState(buildExerciseSessions(done, name, unit), { minSessions, inc });
        if (f?.fatigued) out.push({ exercise: name, reason: f.reason, load: f.load });
    }
    return out;
}

/**
 * Exercises with `name` resolved from the workout-level `exerciseNames` map
 * (persisted exercises carry no inline name).
 */
function withResolvedNames(workout) {
    const exercises = workout?.exercises || {};
    return Object.entries(exercises).map(([key, ex]) => ({
        ...ex,
        name: ex?.name || ex?.machine || workout?.exerciseNames?.[key] || null,
    }));
}

/**
 * A set's weight in `displayUnit`, unrounded (tonnage is only ever a ratio
 * between weeks). 0 for missing/invalid weights.
 */
function normalizedWeight(set, displayUnit) {
    const w = Number(set?.weight);
    if (!w || isNaN(w)) return 0;
    const from = set?.originalUnit || 'lbs';
    const to = displayUnit || 'lbs';
    if (from === to) return w;
    if (from === 'lbs' && to === 'kg') return w * 0.453592;
    if (from === 'kg' && to === 'lbs') return w * 2.20462;
    return w;
}

/**
 * Map exercise name to body part using the exercise database.
 * Falls back to keyword matching if not found in database.
 */
export function getBodyPartForExercise(exerciseName, exerciseDatabase) {
    if (!exerciseName) return null;

    // Check database first
    if (exerciseDatabase && exerciseDatabase.length > 0) {
        const match = exerciseDatabase.find(
            ex => (ex.name || ex.machine || '').toLowerCase() === exerciseName.toLowerCase()
        );
        if (match && match.bodyPart) return match.bodyPart;
    }

    // Keyword fallback. Order matters: specific words before the generic
    // ones they collide with — "lateral raise" before back's "lat", and legs
    // before the bare "press" (Leg Press used to count as shoulders).
    const name = exerciseName.toLowerCase();
    if (name.includes('bench') || name.includes('chest') || name.includes('fly') || name.includes('pec')) return 'Chest';
    if (name.includes('shoulder') || name.includes('delt') || name.includes('lateral raise')) return 'Shoulders';
    if (name.includes('row') || name.includes('pull') || name.includes('lat') || name.includes('back')) return 'Back';
    if (name.includes('squat') || name.includes('leg') || name.includes('lunge') || name.includes('hamstring') || name.includes('quad') || name.includes('calf')) return 'Legs';
    if (name.includes('press')) return 'Shoulders';
    if (name.includes('bicep') || name.includes('curl') || name.includes('tricep') || name.includes('arm') || name.includes('extension')) return 'Arms';
    if (name.includes('core') || name.includes('ab') || name.includes('crunch') || name.includes('plank')) return 'Core';
    if (name.includes('deadlift')) return 'Back';
    if (name.includes('glute') || name.includes('hip thrust')) return 'Glutes';

    return null;
}

/**
 * Calculate weekly volume (working sets) per muscle group from recent workouts.
 * Compare against evidence-based landmarks (MEV / MRV, injected).
 *
 * AP-15a — the count is divided by `weeks`, the number of weeks the input
 * window spans. Callers that pass one week (dashboard, governor) leave it at
 * 1; the coach passes 28 days and weeks:4. Before this the coach summed four
 * weeks and labelled it "weekly", so 12 real chest sets/week read as 48
 * (high) against MRV 22 — phantom overtraining.
 *
 * @param {Array} workouts - Completed workouts inside the window
 * @param {Array} exerciseDatabase - Exercise library with bodyPart fields
 * @param {{weeks?: number, mev?: number, mrv?: number}} [opts]
 * @returns {Array<{bodyPart:string, totalSets:number, weeks:number,
 *   avgWeeklySets:number, weeklySets:number, status:string, recommendation:string|null}>}
 *   `weeklySets` is kept as an alias of `avgWeeklySets` for existing callers.
 */
export function analyzeWeeklyVolume(workouts, exerciseDatabase, {
    weeks = 1, mev = RULE_THRESHOLDS.VOLUME_MEV, mrv = RULE_THRESHOLDS.VOLUME_MRV,
} = {}) {
    const span = Number(weeks) > 0 ? Number(weeks) : 1;
    const volumeByPart = {};

    for (const workout of workouts) {
        if (!workout.exercises) continue;

        for (const exercise of withResolvedNames(workout)) {
            const bodyPart = exercise.bodyPart || getBodyPartForExercise(exercise.name, exerciseDatabase);
            if (!bodyPart) continue;

            const completedSets = (exercise.sets || []).filter(s =>
                s.completed !== false && (s.type || 'working') !== 'warmup'
            ).length;

            volumeByPart[bodyPart] = (volumeByPart[bodyPart] || 0) + completedSets;
        }
    }

    return Object.entries(volumeByPart).map(([part, totalSets]) => {
        const avg = Math.round((totalSets / span) * 10) / 10;
        return {
            bodyPart: part,
            totalSets,
            weeks: span,
            avgWeeklySets: avg,
            weeklySets: avg,
            status: avg < mev ? 'low' : avg > mrv ? 'high' : 'good',
            recommendation: avg < mev
                ? `Add ${Math.ceil(mev - avg)} more this week`
                : avg > mrv
                    ? `Consider reducing ${part} volume to aid recovery`
                    : null,
        };
    });
}

export function shiftDay(dateStr, days) {
    const d = new Date(`${dateStr}T12:00:00`);
    d.setDate(d.getDate() + days);
    return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

/**
 * AP-15a — true per-week average volume over the last `days` days (default
 * 28) ending `today`. Shared by the coach's chat context and its prompt
 * cards so both say the same number. When the user's history starts inside
 * the window, the divisor is the weeks actually covered (rounded up, never
 * below 1) — a two-week-old account isn't averaged over four.
 *
 * @param {Array} allWorkouts - workout history (any order; cancelled skipped)
 * @param {Array} exerciseDatabase
 * @param {{today: string, days?: number, mev?: number, mrv?: number}} opts - today = YYYY-MM-DD
 * @returns {{weeks:number, days:number, volume:Array}} volume = analyzeWeeklyVolume rows
 */
export function averageWeeklyVolume(allWorkouts, exerciseDatabase, { today, days = 28, mev, mrv } = {}) {
    const valid = (allWorkouts || []).filter(w => w?.date && !w.cancelledAt && (!today || w.date <= today));
    if (!today || valid.length === 0) return { weeks: 1, days, volume: [] };
    const cutoff = shiftDay(today, -(days - 1));
    const inWindow = valid.filter(w => w.date >= cutoff);
    const first = valid.reduce((min, w) => (w.date < min ? w.date : min), valid[0].date);
    const maxWeeks = Math.max(1, Math.round(days / 7));
    let weeks = maxWeeks;
    if (first > cutoff) {
        const covered = Math.round((new Date(`${today}T12:00:00`) - new Date(`${first}T12:00:00`)) / 86400000) + 1;
        weeks = Math.min(maxWeeks, Math.max(1, Math.ceil(covered / 7)));
    }
    const landmarks = {};
    if (mev != null) landmarks.mev = mev;
    if (mrv != null) landmarks.mrv = mrv;
    return { weeks, days, volume: analyzeWeeklyVolume(inWindow, exerciseDatabase, { weeks, ...landmarks }) };
}

/**
 * Sum of weight × reps over completed working sets, unit-normalized so a
 * kg-logged session compares honestly with an lbs one. Used only as a ratio
 * between weeks, so the unit itself doesn't matter — just consistency.
 */
export function workoutTonnage(workout) {
    let total = 0;
    for (const exercise of withResolvedNames(workout)) {
        for (const set of exercise.sets || []) {
            if (!set || set.completed === false || (set.type || 'working') === 'warmup') continue;
            const reps = Number(set.reps) || 0;
            if (reps <= 0) continue;
            total += normalizedWeight(set, 'lbs') * reps;
        }
    }
    return total;
}

/**
 * Get ISO week key (YYYY-WXX) for a date string.
 */
export function getISOWeekKey(dateStr) {
    const parts = dateStr.split('-');
    const d = new Date(parseInt(parts[0]), parseInt(parts[1]) - 1, parseInt(parts[2]));
    // ISO week calculation
    const temp = new Date(d.valueOf());
    const dayNum = (d.getDay() + 6) % 7;
    temp.setDate(temp.getDate() - dayNum + 3);
    const firstThursday = temp.valueOf();
    temp.setMonth(0, 1);
    if (temp.getDay() !== 4) {
        temp.setMonth(0, 1 + ((4 - temp.getDay()) + 7) % 7);
    }
    const weekNum = 1 + Math.ceil((firstThursday - temp) / 604800000);
    return `${temp.getFullYear()}-W${String(weekNum).padStart(2, '0')}`;
}

/**
 * If user has trained 5+ days/week for 4+ consecutive weeks,
 * suggest a deload week.
 *
 * A "hard week" was historically 5+ unique training days and nothing else, so
 * a deload trained at full frequency and −35% load counted as hard and the
 * dashboard kept asking for a deload mid-deload (CP-0). A week is now a
 * recovery week — and resets the counter — when any of its sessions is a
 * recovery workout (session intent or label) or when a full-frequency week's
 * tonnage falls `DELOAD_TONNAGE_DROP` below the trailing three-week mean.
 *
 * AP-22 phase 1: `reasons` also lists LEADING signals — effort rising at
 * the same load (fatigueSignals) and low readiness — but they don't flip
 * `needed` yet; that waits for eval fixtures (AP-20).
 *
 * @param {Array} workouts - Recent completed workouts (6+ weeks)
 * @param {object} [thresholds] - RULE_THRESHOLDS shape (Config on the client)
 * @param {{today?:string, unit?:string, inc?:number}} [opts] - for the fatigue reasons
 * @returns {{ needed: boolean, consecutiveHardWeeks: number, inRecoveryWeek: boolean,
 *   reasons: string[], fatigue: Array<{exercise:string, reason:string}>, readinessLow: boolean } | null}
 */
/**
 * AP-22 phase 2: when the run is one week short of DELOAD_CONSECUTIVE_WEEKS
 * and the leading signals agree (effort rising on 2+ main lifts, or low
 * readiness), the deload is due a week early — `source:'fatigue'`.
 * `primaries` = main-lift names; null counts every fatigued exercise.
 */
export function checkDeloadNeeded(workouts, thresholds = RULE_THRESHOLDS, { today = null, unit = 'lbs', inc = 5, primaries = null } = {}) {
    if (!workouts || workouts.length === 0) return null;
    const t = { ...RULE_THRESHOLDS, ...(thresholds || {}) };

    // Group workouts by ISO week
    const weekMap = {};

    for (const workout of workouts) {
        if (!workout.date) continue;
        const weekKey = getISOWeekKey(workout.date);
        if (!weekMap[weekKey]) weekMap[weekKey] = { days: new Set(), tonnage: 0, labelled: false };
        const wk = weekMap[weekKey];
        wk.days.add(workout.date);
        wk.tonnage += workoutTonnage(workout);
        if (isRecoveryWorkout(workout)) wk.labelled = true;
    }

    // Sort weeks newest first
    const sortedWeeks = Object.entries(weekMap)
        .sort((a, b) => b[0].localeCompare(a[0]))
        .map(([, wk]) => wk);

    const isRecoveryWeek = (i) => {
        const wk = sortedWeeks[i];
        if (wk.labelled) return true;
        // Tonnage rule only for full-frequency weeks: a partial current week
        // (Monday, one session) is low-tonnage for a different reason and the
        // day-count rule already handles it.
        if (wk.days.size < t.DELOAD_DAYS_PER_WEEK || wk.tonnage <= 0) return false;
        const prior = sortedWeeks.slice(i + 1, i + 4).filter(p => p.tonnage > 0);
        if (prior.length < 2) return false;
        const mean = prior.reduce((s, p) => s + p.tonnage, 0) / prior.length;
        return wk.tonnage < mean * (1 - t.DELOAD_TONNAGE_DROP);
    };

    // Count consecutive hard weeks, newest first; a recovery week ends the run.
    let consecutiveHardWeeks = 0;
    let inRecoveryWeek = false;
    for (let i = 0; i < sortedWeeks.length; i++) {
        if (isRecoveryWeek(i)) {
            if (i === 0) inRecoveryWeek = true;
            break;
        }
        if (sortedWeeks[i].days.size >= t.DELOAD_DAYS_PER_WEEK) {
            consecutiveHardWeeks++;
        } else {
            break;
        }
    }

    const byWeeks = consecutiveHardWeeks >= t.DELOAD_CONSECUTIVE_WEEKS;
    const reasons = [];
    if (byWeeks) reasons.push(`${consecutiveHardWeeks} hard weeks in a row`);
    const fatigue = inRecoveryWeek ? [] : fatigueSignals(workouts, { today, unit, inc, minSessions: t.PLATEAU_MIN_SESSIONS });
    for (const f of fatigue) reasons.push(`${f.exercise}: ${f.reason}`);
    const ready = readinessState(workouts, { today, days: t.READINESS_WINDOW_DAYS, lowCount: t.READINESS_LOW_COUNT });
    const readinessLow = ready.readinessLow && !inRecoveryWeek;
    if (readinessLow) reasons.push(`readiness ≤2/5 on ${ready.low} of ${ready.of} check-ins in the last ${t.READINESS_WINDOW_DAYS} days`);

    const main = Array.isArray(primaries) ? new Set(primaries.map(n => String(n).trim().toLowerCase())) : null;
    const fatiguedMain = main ? fatigue.filter(f => main.has(String(f.exercise).trim().toLowerCase())) : fatigue;
    const early = !byWeeks && !inRecoveryWeek
        && consecutiveHardWeeks >= Math.max(1, t.DELOAD_CONSECUTIVE_WEEKS - 1)
        && (fatiguedMain.length >= 2 || readinessLow);
    if (early) reasons.unshift(`${consecutiveHardWeeks} hard weeks and ${fatiguedMain.length >= 2 ? `effort rising on ${fatiguedMain.length} main lifts` : 'low readiness'} — a week early`);
    const needed = byWeeks || early;

    return {
        needed,
        source: needed ? (early ? 'fatigue' : 'weeks') : null,
        consecutiveHardWeeks,
        inRecoveryWeek,
        reasons,
        fatigue,
        fatiguedMain: fatiguedMain.map(f => f.exercise),
        readinessLow,
    };
}
