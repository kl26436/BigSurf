// Exercise rotation (CP-4) — the variety engine.
//
// Given a template and the user's mapped equipment at one gym, pick a fresh
// machine for every ACCESSORY slot that trains the same movement pattern,
// preferring never-used gear, then the longest idle. Primaries and
// secondaries never rotate — they are the lifts progress is measured on, and
// rotating them destroys the progression signal (Layer 1 rule).
//
// Pure and deterministic (no randomness, stable tie-breaks) so the server
// and client compute the same answer and the mirror is parity-testable.
//
// MIRRORED: functions/exercise-rotation.js is generated by
//   node scripts/sync-mirror.mjs js/core/features/exercise-rotation.js functions/exercise-rotation.js

import { inferPattern, inferRole, patternsForEquipment } from './movement-patterns.js';

const ROTATABLE_ROLES = new Set(['accessory', 'core']);

function nameOf(x) {
    return (x?.machine || x?.name || '').trim();
}

/**
 * Enrich a template row with library data (tags, explicit pattern) so role
 * and pattern inference has more than a bare name to go on.
 */
function enrich(row, lookup) {
    const lib = (lookup && lookup(nameOf(row))) || null;
    return {
        ...(lib || {}),
        ...row,
        name: nameOf(row),
        tags: row.tags || lib?.tags || [],
        pattern: row.pattern || lib?.pattern || undefined,
    };
}

/** Staleness key: never-used sorts before everything, then oldest first. */
function staleness(doc) {
    return doc.lastUsed ? String(doc.lastUsed).slice(0, 10) : '';
}

function reasonFor(doc) {
    if (!doc.lastUsed) return 'never used';
    const d = String(doc.lastUsed).slice(0, 10);
    return `idle since ${d.slice(0, 7)}`;
}

/**
 * Every machine at the gym that trains `pattern`, paired with the exercise it
 * trains in that pattern, stalest first (never-used, then longest idle).
 * Shared by selectRotation (one pick per slot) and rankRotationCandidates
 * (the ranked list the coach shows).
 */
function patternCandidates({ pattern, atGym, lookup, skipEquipment = () => false, skipName = () => false }) {
    const candidates = [];
    for (const doc of atGym) {
        const key = doc.name.toLowerCase();
        if (skipEquipment(key)) continue;
        if (!patternsForEquipment(doc, lookup).includes(pattern)) continue;
        // The exercise this machine trains in THIS pattern.
        const exName = (doc.exerciseTypes || []).find(n => {
            const ex = (lookup && lookup(n)) || { name: n };
            return inferPattern(ex) === pattern;
        }) || (inferPattern({ name: [doc.function, doc.name].filter(Boolean).join(' ') }) === pattern ? doc.name : null);
        if (!exName) continue;
        if (skipName(exName.toLowerCase())) continue;
        candidates.push({ doc, exName });
    }
    candidates.sort((a, b) =>
        staleness(a.doc).localeCompare(staleness(b.doc))
        || a.doc.name.localeCompare(b.doc.name)
        || a.exName.localeCompare(b.exName));
    return candidates;
}

function atGymOf(equipment, location) {
    return (equipment || []).filter(doc => {
        if (!doc || !doc.name) return false;
        if (!location) return true;
        return Array.isArray(doc.locations) && doc.locations.some(l => String(l).toLowerCase() === String(location).toLowerCase());
    });
}

/**
 * AP-23a — query mode: ranked same-pattern alternatives for ONE exercise (or
 * a pattern), for the coach's get_rotation_candidates. Same ranking as
 * selectRotation; nothing is written.
 *
 * @param {object} args
 * @param {string} [args.exercise] - the exercise to replace (its pattern is inferred)
 * @param {string} [args.pattern] - or an explicit pattern
 * @param {Array}  args.equipment - equipment docs
 * @param {string|null} [args.location] - gym name; null = all equipment
 * @param {(name:string)=>object|undefined} [args.lookup]
 * @param {string[]} [args.exclude] - exercise names not to offer (e.g. already in the workout)
 * @param {number} [args.limit]
 * @returns {{pattern:string|null, role:string|null, candidates:Array<{name:string, equipment:string,
 *   pattern:string, reason:string, lastUsed:string|null}>}}
 */
export function rankRotationCandidates({ exercise = null, pattern = null, equipment = [], location = null, lookup, exclude = [], limit = 5 } = {}) {
    const row = exercise ? enrich({ name: exercise }, lookup) : null;
    const p = pattern || (row ? inferPattern(row) : null);
    if (!p) return { pattern: null, role: row ? inferRole(row, 0) : null, candidates: [] };
    const skip = new Set([...(exclude || []), ...(exercise ? [exercise] : [])].map(n => String(n).toLowerCase()));
    const ranked = patternCandidates({ pattern: p, atGym: atGymOf(equipment, location), lookup, skipName: (k) => skip.has(k) });
    const seen = new Set();
    const candidates = [];
    for (const c of ranked) {
        const k = c.exName.toLowerCase();
        if (seen.has(k)) continue;
        seen.add(k);
        candidates.push({
            name: c.exName, equipment: c.doc.name, pattern: p, reason: reasonFor(c.doc),
            lastUsed: c.doc.lastUsed ? String(c.doc.lastUsed).slice(0, 10) : null,
        });
        if (candidates.length >= limit) break;
    }
    return { pattern: p, role: row ? inferRole(row, 0) : null, candidates };
}

/**
 * Plan accessory swaps for one template.
 *
 * @param {object} args
 * @param {Array}  args.exercises - template rows [{ machine|name, role?, pattern?, equipment?, sets, reps }]
 * @param {Array}  args.equipment - equipment docs [{ name, exerciseTypes[], locations[], lastUsed, function }]
 * @param {string|null} [args.location] - gym name; null = all equipment
 * @param {(name:string)=>object|undefined} [args.lookup] - exercise-by-name resolver (library)
 * @returns {{ swaps: Array<{index:number, from:string, to:string, equipment:string, pattern:string, reason:string}>,
 *             held: Array<{index:number, name:string, role:string, reason:string}> }}
 */
export function selectRotation({ exercises = [], equipment = [], location = null, lookup } = {}) {
    const rows = exercises.map(r => enrich(r, lookup));
    const roles = rows.map((r, i) => inferRole(r, i));
    const patterns = rows.map(r => inferPattern(r));

    const atGym = (equipment || []).filter(doc => {
        if (!doc || !doc.name) return false;
        if (!location) return true;
        return Array.isArray(doc.locations) && doc.locations.includes(location);
    });

    // Gear the held slots use stays theirs; names already in the template
    // are not "fresh" no matter what machine they run on.
    const reservedEquipment = new Set();
    const templateNames = new Set(rows.map(r => r.name.toLowerCase()));
    rows.forEach((r, i) => {
        if (!ROTATABLE_ROLES.has(roles[i]) && r.equipment) reservedEquipment.add(r.equipment.toLowerCase());
    });

    const swaps = [];
    const held = [];
    const takenEquipment = new Set();
    const takenNames = new Set();

    rows.forEach((row, index) => {
        const role = roles[index];
        const pattern = patterns[index];
        if (!ROTATABLE_ROLES.has(role)) {
            held.push({ index, name: row.name, role, reason: `${role} — progression spine` });
            return;
        }
        if (!pattern) {
            held.push({ index, name: row.name, role, reason: 'no movement pattern' });
            return;
        }
        const currentEquip = (row.equipment || '').toLowerCase();
        const candidates = patternCandidates({
            pattern, atGym, lookup,
            skipEquipment: (key) => key === currentEquip || reservedEquipment.has(key) || takenEquipment.has(key),
            skipName: (exKey) => exKey === row.name.toLowerCase() || templateNames.has(exKey) || takenNames.has(exKey),
        });
        const pick = candidates[0];
        if (!pick) {
            held.push({ index, name: row.name, role, reason: 'no alternative at this gym' });
            return;
        }
        takenEquipment.add(pick.doc.name.toLowerCase());
        takenNames.add(pick.exName.toLowerCase());
        swaps.push({
            index, from: row.name, to: pick.exName, equipment: pick.doc.name,
            pattern, reason: reasonFor(pick.doc),
        });
    });

    return { swaps, held };
}

/**
 * Apply a rotation plan to a template's exercise list: the swapped rows keep
 * sets/reps and drop the old machine's weight (a new machine has no earned
 * load), record what they replaced, and inherit body part from the library.
 * Returns a NEW array; the input is not mutated.
 */
export function applyRotation(exercises = [], swaps = [], { lookup, today = null } = {}) {
    const byIndex = new Map(swaps.map(s => [s.index, s]));
    return exercises.map((row, i) => {
        const s = byIndex.get(i);
        if (!s) return row;
        const lib = (lookup && lookup(s.to)) || {};
        const next = { ...row };
        delete next.weight;
        delete next.equipmentId;
        if ('machine' in next || !('name' in next)) next.machine = s.to; else next.name = s.to;
        if ('name' in next && 'machine' in next) next.name = s.to;
        next.equipment = s.equipment;
        if (lib.bodyPart) next.bodyPart = lib.bodyPart;
        if (lib.equipmentType) next.equipmentType = lib.equipmentType;
        if (row.pattern || lib.pattern) next.pattern = row.pattern || lib.pattern;
        next.rotatedFrom = s.from;
        if (today) next.rotatedAt = today;
        return next;
    });
}
