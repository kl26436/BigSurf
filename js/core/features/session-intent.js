// Session intent (AP-6) — what TODAY's session is for, decided once.
//
// Before this, "deload" was a side effect of one button: the dashboard hero
// applied the program's −35% after autofill, and every other way into a
// workout (Workouts tab, repeat from history, resume, add/replace mid-session)
// had no idea. The progression rules read history alone, so a deload week's
// card still said "bump to 230". The intent is computed at start, stored on
// the workout doc (savedData.sessionIntent), and every consumer reads it.
//
// Pure — inputs injected; no AppState.
//
// MIRRORED: functions/session-intent.js is generated by
//   node scripts/sync-mirror.mjs js/core/features/session-intent.js functions/session-intent.js
// (tests/unit/movement-patterns-mirror.test.js enforces parity) — the
// server's rules verdicts (coach-rules.js) need the same intent.

import { weekTargetEffects, isDeloadTarget, describeWeekTarget, deriveProgramWeek } from './week-targets.js';

const RECOVERY_LABEL = /deload|recovery/i;

/** Default load cut for a manual (no-program) deload. */
export const MANUAL_DELOAD_WEIGHT_PCT = -30;

function shiftDays(dateStr, days) {
    const d = new Date(`${dateStr}T12:00:00`);
    d.setDate(d.getDate() + days);
    return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

/** Last day (inclusive) of a manual deload window, or null. */
export function manualDeloadEnd(manualDeload) {
    if (!manualDeload?.from) return null;
    const weeks = Math.max(1, Number(manualDeload.weeks) || 1);
    return shiftDays(manualDeload.from, weeks * 7 - 1);
}

/** Is `today` inside the manual deload window? */
export function isManualDeloadActive(manualDeload, today) {
    const end = manualDeloadEnd(manualDeload);
    return !!end && !!today && today >= manualDeload.from && today <= end;
}

const baseIntent = () => ({
    mode: 'build', weightPct: null, setDelta: null, repRange: null, rpeTarget: null,
    label: null, week: null, weeks: null, source: 'none', reason: '',
});

/**
 * Precedence: (1) the active program's current week, when it changes the
 * session; (2) a manual deload window; (3) a legacy deload/recovery
 * sessionLabel (resuming a doc started before intents existed); (4) plain
 * build / freestyle. Intent is computed for every trust level — trust gates
 * APPLYING set/rep deltas, not knowing what week it is.
 *
 * @returns {{mode:'build'|'deload'|'peak'|'freestyle', weightPct:number|null,
 *   setDelta:number|null, repRange:number[]|null, rpeTarget:number|null,
 *   label:string|null, week:number|null, weeks:number|null,
 *   source:'program'|'manual'|'label'|'none', reason:string}}
 */
export function getSessionIntent({ program = null, today, manualDeload = null, sessionLabel = null, freestyle = false } = {}) {
    if (program?.startDate && program.active !== false && today) {
        const { week, target, finished } = deriveProgramWeek(program, today);
        if (Number.isFinite(week) && week >= 1 && !finished && target) {
            const fx = weekTargetEffects(target);
            if (fx.changesSession) {
                const deload = isDeloadTarget(target);
                const peak = !deload && ((fx.weightPct != null && fx.weightPct > 0) || (fx.rpeTarget != null && fx.rpeTarget >= 9));
                const desc = describeWeekTarget(target);
                return {
                    mode: deload ? 'deload' : (peak ? 'peak' : 'build'),
                    weightPct: fx.weightPct, setDelta: fx.setDelta, repRange: fx.repRange, rpeTarget: fx.rpeTarget,
                    label: target.label, week, weeks: program.weeks || 1,
                    source: 'program',
                    reason: `Week ${week} of ${program.name || 'your program'}: ${target.label}${desc ? ` (${desc})` : ''}`,
                };
            }
        }
    }
    if (isManualDeloadActive(manualDeload, today)) {
        const pct = typeof manualDeload.weightPct === 'number' ? manualDeload.weightPct : MANUAL_DELOAD_WEIGHT_PCT;
        return {
            ...baseIntent(),
            mode: 'deload', weightPct: pct, label: 'Deload', source: 'manual',
            reason: `Deload week through ${manualDeloadEnd(manualDeload)}`,
        };
    }
    if (sessionLabel && RECOVERY_LABEL.test(sessionLabel)) {
        // Weights on a legacy labelled session were already scaled when it
        // started — know it's a deload, don't scale again.
        return { ...baseIntent(), mode: 'deload', label: sessionLabel, source: 'label', reason: `Session labelled ${sessionLabel}` };
    }
    return { ...baseIntent(), mode: freestyle ? 'freestyle' : 'build' };
}

/** One intent for a single session the user flagged mid-workout. */
export function sessionOnlyDeloadIntent() {
    return {
        ...baseIntent(),
        mode: 'deload', weightPct: MANUAL_DELOAD_WEIGHT_PCT, label: 'Deload', source: 'manual',
        reason: 'This session marked as a deload',
    };
}

/** A completed workout that was a deload/recovery session. */
export function isRecoveryWorkout(w) {
    return !!w && (w.sessionIntent?.mode === 'deload' || RECOVERY_LABEL.test(w.sessionLabel || ''));
}

/** "Deload · −35% weight · 12–15 reps" — '' for a plain build session. */
export function describeIntent(intent) {
    if (!intent || intent.mode === 'build' || intent.mode === 'freestyle') return '';
    const levers = describeWeekTarget(intent);
    return [intent.label || (intent.mode === 'deload' ? 'Deload' : 'Heavy'), levers].filter(Boolean).join(' · ');
}
