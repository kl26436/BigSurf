// Coach rules verdicts (AP-16) — the rules engine's answers, handed to the
// model as facts.
//
// Before this the coach got 30 raw workouts and a prose description of the
// progression matrix, and was asked to re-derive what progression.js already
// knows. It did that badly and slowly, and it was the only path by which the
// chat could disagree with the set rows. Now the app computes every verdict
// with a number and a threshold — today's target per exercise, the stall
// rung, whether a deload is due, MRV headroom, the progress scoreboard — and
// the prompt rule is "explain it, don't override it".
//
// Pure: data in, verdicts out. The client builds the context block from it
// (ai-coach-ui.js); the server's `get_verdicts` tool and weekly review call
// the generated mirror, so all three read one computation.
//
// MIRRORED: functions/coach-rules.js is generated by
//   node scripts/sync-mirror.mjs js/core/features/coach-rules.js functions/coach-rules.js
// (tests/unit/movement-patterns-mirror.test.js enforces parity).

import { buildExerciseSessions, progressionTarget, weightIncrement } from './progression.js';
import { getSessionIntent, describeIntent } from './session-intent.js';
import { analyzeWeeklyVolume, checkDeloadNeeded, getISOWeekKey, readinessState, RULE_THRESHOLDS } from './training-rules.js';
import { buildScoreboard, formatScoreboardContext, pickPrimaries, bestE1rmBetween } from './progress-scoreboard.js';
import { inferRole } from './movement-patterns.js';
import { deriveProgramWeek } from './week-targets.js';
import { fatigueSignals, shiftDay } from './training-rules.js';

const DAY_KEYS = ['mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun'];
/** Enough to cover today plus the rest of the week's plan, small enough to stay a short block. */
const MAX_VERDICT_EXERCISES = 18;
/** Without a week plan, verdicts cover the most recently used templates. */
const FALLBACK_TEMPLATES = 3;

const norm = (s) => String(s || '').trim().toLowerCase();

function dayKeyOf(today) {
    const d = new Date(`${today}T12:00:00`);
    return DAY_KEYS[(d.getDay() + 6) % 7];
}

/** Spelling of each exercise as history knows it (buildExerciseSessions matches exactly). */
function historySpellings(workouts) {
    const out = new Map();
    const sorted = [...(workouts || [])].filter(w => w?.date).sort((a, b) => b.date.localeCompare(a.date));
    for (const w of sorted) {
        for (const [k, ex] of Object.entries(w.exercises || {})) {
            const name = w.exerciseNames?.[k] || ex?.name || ex?.machine;
            if (name && !out.has(norm(name))) out.set(norm(name), name);
        }
    }
    return out;
}

/**
 * Which exercises get a verdict: today's planned workout first, then the
 * rest of the week plan from tomorrow on; with no week plan, the three most
 * recently used templates. Deduped by name, capped.
 * @returns {Array<{name:string, repTarget:number|null, template:string, today:boolean}>}
 */
export function pickVerdictExercises({ templates = [], weekPlan = null, today, workouts = [] } = {}) {
    const active = (templates || []).filter(t => t && !t.archived && !t.isHidden && Array.isArray(t.exercises));
    const byId = new Map(active.map(t => [t.id, t]));
    const ordered = [];
    const todayKey = today ? dayKeyOf(today) : null;
    if (weekPlan?.days && todayKey) {
        const start = DAY_KEYS.indexOf(todayKey);
        for (let i = 0; i < DAY_KEYS.length; i++) {
            const day = DAY_KEYS[(start + i) % 7];
            const t = byId.get(weekPlan.days[day]);
            if (t && !ordered.some(o => o.t === t)) ordered.push({ t, today: i === 0 });
        }
    }
    if (ordered.length === 0) {
        const lastUse = new Map();
        for (const w of workouts || []) {
            if (!w?.workoutType || !w.completedAt || w.cancelledAt) continue;
            const k = norm(w.workoutType);
            if (!lastUse.has(k) || w.date > lastUse.get(k)) lastUse.set(k, w.date);
        }
        active
            .map(t => ({ t, last: lastUse.get(norm(t.name || t.day)) || '' }))
            .filter(x => x.last)
            .sort((a, b) => b.last.localeCompare(a.last))
            .slice(0, FALLBACK_TEMPLATES)
            .forEach(x => ordered.push({ t: x.t, today: false }));
    }
    const out = [];
    const seen = new Set();
    for (const { t, today: isToday } of ordered) {
        for (const ex of t.exercises) {
            const name = ex?.machine || ex?.name;
            if (!name || seen.has(norm(name))) continue;
            seen.add(norm(name));
            const repTarget = Number(ex.defaultReps || ex.reps) || null;
            out.push({ name, repTarget, template: t.name || t.day || 'Workout', today: isToday });
            if (out.length >= MAX_VERDICT_EXERCISES) return out;
        }
    }
    return out;
}

/**
 * @param {object} args
 * @param {Array} args.workouts - completed history, any order
 * @param {Array} [args.templates]
 * @param {object|null} [args.weekPlan] - {days:{mon:templateId|null,…}, restDays}
 * @param {object|null} [args.program] - active program doc
 * @param {object|null} [args.manualDeload] - settings.manualDeload
 * @param {object|null} [args.intent] - an in-progress session's stored intent (wins)
 * @param {'lbs'|'kg'} [args.unit]
 * @param {number[]} [args.plates] - plate inventory for the unit (weight jump)
 * @param {string} args.today - YYYY-MM-DD local
 * @param {Array} [args.exerciseDatabase] - library with bodyPart (volume mapping)
 * @param {object} [args.thresholds] - RULE_THRESHOLDS shape
 */
export function computeVerdicts({
    workouts = [], templates = [], weekPlan = null, program = null, manualDeload = null,
    intent = null, unit = 'lbs', plates = null, today, exerciseDatabase = [], thresholds = RULE_THRESHOLDS,
} = {}) {
    const u = unit === 'kg' ? 'kg' : 'lbs';
    const t = { ...RULE_THRESHOLDS, ...(thresholds || {}) };
    const done = (workouts || []).filter(w => w?.date && w.completedAt && !w.cancelledAt && (!today || w.date <= today));
    const sessionIntent = intent || getSessionIntent({ program, today, manualDeload });
    const increment = weightIncrement(u, plates);
    const spellings = historySpellings(done);

    const exercises = pickVerdictExercises({ templates, weekPlan, today, workouts: done }).map((pick) => {
        const name = spellings.get(norm(pick.name)) || pick.name;
        const sessions = buildExerciseSessions(done, name, u);
        const target = progressionTarget(sessions, u, pick.repTarget, increment, sessionIntent);
        const base = { name, template: pick.template, today: pick.today };
        if (!target) return { ...base, action: 'no-history' };
        const last = sessions[0];
        return {
            ...base,
            action: target.action,
            weight: target.weight,
            reps: target.reps,
            bumped: target.bumped,
            stalled: target.stalled,
            ...(target.rung ? { rung: target.rung, stallRun: target.stallRun } : {}),
            ...(target.early ? { early: true } : {}),
            last: { weight: last.topWeight, reps: last.topReps || last.maxReps || null, date: last.date },
            // AP-22 phase 2 — progressionTarget already acted on it.
            ...(target.fatigued ? { fatigue: target.fatigueReason } : {}),
        };
    });

    const thisWeek = today ? getISOWeekKey(today) : null;
    const weekWorkouts = thisWeek ? done.filter(w => getISOWeekKey(w.date) === thisWeek) : [];
    const volume = analyzeWeeklyVolume(weekWorkouts, exerciseDatabase, { mev: t.VOLUME_MEV, mrv: t.VOLUME_MRV })
        .map(v => ({
            bodyPart: v.bodyPart,
            sets: v.totalSets,
            mrv: t.VOLUME_MRV,
            headroom: t.VOLUME_MRV - v.totalSets,
            status: v.totalSets > t.VOLUME_MRV ? 'over' : (v.totalSets >= t.VOLUME_MRV - 2 ? 'near' : 'ok'),
        }))
        .sort((a, b) => b.sets - a.sets);

    return {
        today,
        unit: u,
        increment,
        intent: {
            mode: sessionIntent.mode,
            label: sessionIntent.label,
            source: sessionIntent.source,
            reason: sessionIntent.reason || '',
            levers: describeIntent(sessionIntent),
        },
        exercises,
        deload: checkDeloadNeeded(done, t, { today, unit: u, inc: increment, primaries: pickPrimaries({ templates, workouts: done, today }).map(p => p.name) }),
        readiness: readinessState(done, { today, days: t.READINESS_WINDOW_DAYS, lowCount: t.READINESS_LOW_COUNT }),
        volume,
        // AP-17 — the app's thresholds, stated to the model (the prompt no
        // longer carries textbook MEV/MRV ranges that disagreed with these).
        landmarks: { mev: t.VOLUME_MEV, mrv: t.VOLUME_MRV },
        scoreboard: buildScoreboard({
            workouts: done, templates, unit: u, today,
            config: { patternTarget: t.PATTERN_TARGET_SETS, mrv: t.VOLUME_MRV, increment },
        }),
    };
}

/** One exercise verdict in words. */
export function verdictLine(v, unit) {
    const wr = (w, r) => `${w}${r ? `×${r}` : ''} ${unit}`;
    const lastStr = v.last ? `last ${wr(v.last.weight, v.last.reps)} on ${v.last.date}` : '';
    switch (v.action) {
        case 'bump': return `bump → ${wr(v.weight, v.reps)} (${lastStr} hit the target)`;
        case 'consolidate':
            return v.fatigue
                ? `hold ${wr(v.weight, v.reps)} — reps earned a bump but effort is climbing, own it first (${lastStr})`
                : `hold ${wr(v.weight, v.reps)} — went up last session, own it first (${lastStr})`;
        case 'chase-rep':
            return v.rung
                ? `stall rung 1 (${v.stallRun} sessions at ${v.weight}) — hold ${v.weight} ${unit}, chase ${v.reps} reps`
                : `hold ${v.weight} ${unit}, chase ${v.reps} reps (${lastStr})`;
        case 'back-off': return `stall rung 2${v.early ? ' a rung early — effort rising' : ''} (${v.stallRun} sessions flat) — back off to ${wr(v.weight, v.reps)} for two sessions, then rebuild`;
        case 'rotate': return `stall rung 3 (${v.stallRun} sessions flat at ${v.weight}) — rotate to a similar movement this block`;
        case 'deload': return `deload — ${wr(v.weight, v.reps)}, two reps in the tank (${lastStr})`;
        case 'start': return `hold ${wr(v.weight, v.reps)} — not enough history for a call yet`;
        default: return 'no logged history — start conservative';
    }
}

/**
 * The `Rules verdicts` context block. Authoritative by prompt contract:
 * the model explains these and may deviate only by saying so explicitly.
 * @returns {string} '' when there is nothing to say
 */
export function formatVerdictsContext(v) {
    if (!v) return '';
    const lines = ['Rules verdicts (computed by the app with the same rules as the set rows — authoritative: explain them, don\'t override them; to deviate say "The rule says X; I\'d deviate because Y"):'];
    if (v.intent?.mode === 'deload' || v.intent?.mode === 'peak') {
        lines.push(`Today's session: ${v.intent.levers || v.intent.label || v.intent.mode}${v.intent.reason ? ` — ${v.intent.reason}` : ''}`);
    }
    if (v.deload) {
        const d = v.deload;
        let s = `not due (${d.consecutiveHardWeeks} hard week${d.consecutiveHardWeeks === 1 ? '' : 's'} running)`;
        if (d.inRecoveryWeek) s = 'in a recovery week now';
        else if (d.needed && d.source === 'fatigue') s = `DUE a week early — ${d.reasons[0]}`;
        else if (d.needed) s = `DUE — ${d.consecutiveHardWeeks} hard weeks in a row`;
        // AP-22 — the leading signals behind (or short of) the call.
        const early = (d.reasons || []).filter(r => !/hard weeks/.test(r));
        if (early.length) s += `; early fatigue signs: ${early.join('; ')}`;
        lines.push(`Deload check: ${s}`);
    }
    if (v.readiness?.of) {
        const r = v.readiness;
        lines.push(`Readiness (last check-ins): avg ${r.avg}/5, ${r.low} of ${r.of} at ≤2/5${r.readinessLow ? ' — LOW' : ''}`);
    }
    if (v.exercises?.length) {
        lines.push(`Progression targets (weights in ${v.unit}, smallest jump ${v.increment}):`);
        for (const e of v.exercises) {
            const fatigue = e.fatigue ? ` · fatigue: ${e.fatigue} (already in the target — don't push past it)` : '';
            lines.push(`- ${e.name} (${e.template}${e.today ? ', today' : ''}): ${verdictLine(e, v.unit)}${fatigue}`);
        }
    }
    if (v.landmarks) lines.push(`Volume landmarks: MEV ${v.landmarks.mev} · MRV ${v.landmarks.mrv} working sets per muscle per week`);
    if (v.volume?.length) {
        const mrv = v.volume[0].mrv;
        const vol = v.volume.map((x) => {
            if (x.status === 'over') return `${x.bodyPart} ${x.sets} (OVER by ${-x.headroom})`;
            return `${x.bodyPart} ${x.sets} (${x.headroom} left)`;
        });
        lines.push(`Volume this week so far vs MRV ${mrv}: ${vol.join(' · ')}`);
    }
    const sb = formatScoreboardContext(v.scoreboard);
    if (!v.exercises?.length && !v.volume?.length && !v.deload && !sb) return '';
    return `${lines.join('\n')}\n${sb}`;
}

// ── Block retrospective (AP-23c) ─────────────────────────────────────

const round1 = (n) => Math.round(n * 10) / 10;

/**
 * How a block went — the start of every "what's next?" conversation:
 * per main lift, best e1RM at the start vs the end; per week, planned vs
 * trained days, the fatigue flags and the movement patterns that sat under
 * target; which accessories on the split were used and which never were.
 * Works on the active block (to date) or a finished one.
 *
 * @param {object} args
 * @param {object} args.program - program doc ({name, goal, weeks, startDate, weekTargets, split})
 * @param {Array} args.workouts - completed history, any order
 * @param {Array} [args.templates]
 * @param {'lbs'|'kg'} [args.unit]
 * @param {string} args.today - YYYY-MM-DD
 * @param {number[]} [args.plates]
 * @returns {object|null}
 */
export function buildBlockRetrospective({ program, workouts = [], templates = [], unit = 'lbs', today, plates = null } = {}) {
    if (!program?.startDate || !today) return null;
    const u = unit === 'kg' ? 'kg' : 'lbs';
    const weeks = Math.max(1, Number(program.weeks) || 1);
    const start = program.startDate;
    const blockEnd = shiftDay(start, weeks * 7 - 1);
    const end = today < blockEnd ? today : blockEnd;
    if (end < start) return null;
    const done = (workouts || []).filter(w => w?.date && w.completedAt && !w.cancelledAt && w.date <= end);
    const inBlock = done.filter(w => w.date >= start);
    const inc = weightIncrement(u, plates);
    const currentWeek = Math.min(weeks, Math.max(1, deriveProgramWeek(program, end).week));

    const primaries = pickPrimaries({ templates, workouts: done, today: end }).map((p) => {
        const e1rmStart = bestE1rmBetween(done, p.name, u, start, shiftDay(start, 13))
            ?? bestE1rmBetween(done, p.name, u, shiftDay(start, -28), shiftDay(start, -1));
        const e1rmEnd = bestE1rmBetween(done, p.name, u, shiftDay(end, -13), end);
        return {
            name: p.name, pattern: p.pattern, e1rmStart, e1rmEnd,
            delta: e1rmStart && e1rmEnd ? round1(e1rmEnd - e1rmStart) : null,
            deltaPct: e1rmStart && e1rmEnd ? round1(((e1rmEnd - e1rmStart) / e1rmStart) * 100) : null,
        };
    });

    const split = program.split || {};
    const splitIds = Object.values(split).filter(id => id && id !== 'rest');
    const planned = splitIds.length;
    const weekRows = [];
    for (let w = 1; w <= currentWeek; w++) {
        const wStart = shiftDay(start, (w - 1) * 7);
        const wEndFull = shiftDay(wStart, 6);
        const wEnd = wEndFull < end ? wEndFull : end;
        const trained = new Set(inBlock.filter(x => x.date >= wStart && x.date <= wEnd).map(x => x.date)).size;
        const target = (program.weekTargets || []).find(t => t.week === w) || null;
        const upTo = done.filter(x => x.date <= wEnd);
        const sb = buildScoreboard({ workouts: upTo, templates, unit: u, today: wEnd, config: { increment: inc } });
        weekRows.push({
            week: w,
            label: target?.label || 'baseline',
            planned,
            trained,
            complete: wEnd === wEndFull,
            fatigue: fatigueSignals(upTo, { today: wEnd, unit: u, inc }).map(f => f.exercise),
            patternsUnder: sb.patterns.filter(p => p.status === 'under').map(p => p.label),
        });
    }

    const byId = new Map((templates || []).map(t => [t.id, t]));
    const usedNames = new Set();
    for (const w of inBlock) {
        for (const [k, ex] of Object.entries(w.exercises || {})) {
            const n = w.exerciseNames?.[k] || ex?.name || ex?.machine;
            if (n) usedNames.add(n.trim().toLowerCase());
        }
    }
    const used = [];
    const neverUsed = [];
    const seen = new Set();
    for (const id of new Set(splitIds)) {
        const t = byId.get(id);
        (t?.exercises || []).forEach((ex, i) => {
            const name = ex?.machine || ex?.name;
            if (!name || seen.has(name.toLowerCase())) return;
            seen.add(name.toLowerCase());
            if (inferRole(ex, i) === 'primary') return;
            (usedNames.has(name.toLowerCase()) ? used : neverUsed).push(name);
        });
    }

    return {
        scope: 'block',
        program: { name: program.name || 'Program', goal: program.goal || null, weeks, startDate: start, endDate: blockEnd },
        finished: today > blockEnd,
        throughWeek: currentWeek,
        unit: u,
        primaries,
        weeks: weekRows,
        daysTrained: new Set(inBlock.map(w => w.date)).size,
        daysPlanned: planned * weekRows.filter(r => r.complete).length + (weekRows.some(r => !r.complete) ? planned : 0),
        accessories: { used, neverUsed },
    };
}

/** The retrospective as context text. */
export function formatBlockRetrospective(r) {
    if (!r) return '';
    const lines = [`Block retrospective — "${r.program.name}" (${r.program.weeks} weeks from ${r.program.startDate}${r.finished ? ', finished' : `, through week ${r.throughWeek}`}): ${r.daysTrained} of ~${r.daysPlanned} planned days trained`];
    for (const p of r.primaries) {
        const move = p.delta == null ? 'not enough data' : `${p.e1rmStart} → ${p.e1rmEnd} ${r.unit} (${p.delta > 0 ? '+' : ''}${p.delta}, ${p.deltaPct > 0 ? '+' : ''}${p.deltaPct}%)`;
        lines.push(`- ${p.name}: e1RM ${move}`);
    }
    for (const w of r.weeks) {
        const bits = [`${w.trained}/${w.planned} days`];
        if (w.fatigue.length) bits.push(`fatigue: ${w.fatigue.join(', ')}`);
        if (w.patternsUnder.length) bits.push(`under: ${w.patternsUnder.join(', ').toLowerCase()}`);
        lines.push(`- Week ${w.week} (${w.label}): ${bits.join(' · ')}`);
    }
    if (r.accessories.neverUsed.length) lines.push(`Accessories on the split never done this block: ${r.accessories.neverUsed.join(', ')}`);
    return `${lines.join('\n')}\n`;
}
