// Progress scoreboard (AP-21) — "am I getting stronger?" in one object.
//
// Week-to-week numbers on one machine are noise (sleep, exercise order,
// which pin). The unit of progress is ~4 weeks on a handful of main lifts,
// measured as estimated 1RM: best e1RM in the last 28 days vs the 28 before.
// Plus per-pattern set counts so a movement nobody trains (hinge, usually)
// shows up as a gap instead of staying invisible.
//
// Pure: data in, object out — no AppState. The dashboard card, the coach's
// rules-verdicts block and the server's weekly review all call this, so the
// three can never disagree.
//
// MIRRORED: functions/progress-scoreboard.js is generated by
//   node scripts/sync-mirror.mjs js/core/features/progress-scoreboard.js functions/progress-scoreboard.js
// (tests/unit/movement-patterns-mirror.test.js enforces parity).

import { inferPattern, inferRole } from './movement-patterns.js';
import { isRecoveryWorkout } from './session-intent.js';
import { buildExerciseSessions, stallState, fatigueState, sameMachine } from './progression.js';
import { convertToUnit } from './coach-outcomes.js';
import { RULE_THRESHOLDS, shiftDay } from './training-rules.js';
import { describeStuck } from './plain-language.js';

export const SCOREBOARD_WINDOW_DAYS = 28;

/** The six movement patterns a program's main lifts should cover. */
export const SPINE_PATTERNS = [
    'knee-dominant', 'hip-dominant', 'horizontal-push', 'vertical-push', 'horizontal-pull', 'vertical-pull',
];

export const PATTERN_LABELS = {
    'knee-dominant': 'Squat',
    'hip-dominant': 'Hinge',
    'horizontal-push': 'Horizontal push',
    'vertical-push': 'Vertical push',
    'horizontal-pull': 'Horizontal pull',
    'vertical-pull': 'Vertical pull',
    // LB-1 — labelled for display only; not in SPINE_PATTERNS, so never coverage.
    'shrug': 'Shrug',
};

/** Epley is unreliable past ~12 reps — those sets don't estimate a max. */
const E1RM_MAX_REPS = 12;
/** ±2.5% (or one weight jump, whichever is larger) is "flat", not a trend. */
const FLAT_BAND_PCT = 0.025;
const INCREMENT = { lbs: 5, kg: 2.5 };
const MAX_AUTO_PRIMARIES = 6;
const MAX_TAGGED_PRIMARIES = 8;
/** The auto-picked main lifts come from what was trained in the last 8 weeks. */
const AUTO_LOOKBACK_DAYS = 56;

const norm = (s) => String(s || '').trim().toLowerCase();
const round1 = (n) => Math.round(n * 10) / 10;

/** Epley estimated 1RM, 1 decimal; 0 outside 1–12 reps or without a load. */
export function epley1RM(weight, reps) {
    const w = Number(weight);
    const r = Number(reps);
    if (!(w > 0) || !(r >= 1) || r > E1RM_MAX_REPS) return 0;
    return round1(w * (1 + r / 30));
}

const usable = (w, today) => !!(w && w.date && w.completedAt && !w.cancelledAt && w.exercises
    && (!today || w.date <= today));

function eachExercise(w, fn) {
    for (const [k, ex] of Object.entries(w.exercises || {})) {
        const name = w.exerciseNames?.[k] || ex?.name || ex?.machine;
        if (name && ex) fn(name, ex);
    }
}

/** Sets that count as training volume — same rule as analyzeWeeklyVolume. */
function countableSets(ex) {
    return (ex.sets || []).filter(s => s && s.completed !== false && (s.type || 'working') !== 'warmup').length;
}

/**
 * A set's load in `unit`, or 0. `set.weight` is the TOTAL load (on a
 * base-weight machine logging stores plates + base in `weight` and the typed
 * plates in `_plateWeight`), which is what a 1RM estimate wants. The >1000
 * guard matches the app-wide corrupted-entry rule.
 */
function loadOf(set, unit) {
    const w = Number(set?.weight);
    if (!w || w <= 0 || w > 1000) return 0;
    return convertToUnit(w, set.originalUnit || 'lbs', unit);
}

function strengthSets(ex) {
    return (ex.sets || []).filter(s => s && s.completed !== false
        && (s.type || 'working') !== 'warmup' && s.type !== 'dropset' && Number(s.reps) > 0);
}

/**
 * The main lifts the scoreboard tracks. Explicit `role:'primary'` rows in
 * active templates win (the Settings picker writes them); without any, the
 * most-trained compound per spine pattern over the last 8 weeks, max six.
 * @returns {Array<{name:string, pattern:string|null, source:'tagged'|'auto'}>}
 */
export function pickPrimaries({ templates = [], workouts = [], today = null } = {}) {
    const tagged = new Map();
    for (const t of templates || []) {
        if (!t || t.archived || t.isHidden) continue;
        for (const ex of t.exercises || []) {
            if (ex?.role !== 'primary') continue;
            const name = ex.machine || ex.name;
            if (!name || tagged.has(norm(name))) continue;
            tagged.set(norm(name), {
                name, pattern: inferPattern({ ...ex, name }, { equipment: ex.equipment }), source: 'tagged',
                ...(ex.equipment ? { equipment: ex.equipment } : {}), ...(ex.equipmentId ? { equipmentId: ex.equipmentId } : {}),
            });
        }
    }
    if (tagged.size) return [...tagged.values()].slice(0, MAX_TAGGED_PRIMARIES);

    const from = today ? shiftDay(today, -(AUTO_LOOKBACK_DAYS - 1)) : null;
    const counts = new Map();
    for (const w of workouts || []) {
        if (!usable(w, today) || (from && w.date < from) || isRecoveryWorkout(w)) continue;
        eachExercise(w, (name, ex) => {
            // LB-1 — the machine decides a back extension (45° = hinge).
            const pattern = inferPattern({ name }, { equipment: ex.equipment });
            if (!SPINE_PATTERNS.includes(pattern)) return;
            // Index 0 asks "is this a compound?" — a pec deck is horizontal
            // push too, but it isn't where strength is measured.
            if (inferRole({ name }, 0) !== 'primary') return;
            const n = countableSets(ex);
            if (!n) return;
            const key = norm(name);
            const c = counts.get(key) || { name, pattern, sets: 0, last: '' };
            c.sets += n;
            if (w.date > c.last) { c.last = w.date; c.name = name; c.equipment = ex.equipment || null; c.equipmentId = ex.equipmentId || null; }
            counts.set(key, c);
        });
    }
    const best = new Map();
    for (const c of counts.values()) {
        const b = best.get(c.pattern);
        if (!b || c.sets > b.sets || (c.sets === b.sets && c.last > b.last)) best.set(c.pattern, c);
    }
    return SPINE_PATTERNS.map(p => best.get(p)).filter(Boolean)
        .slice(0, MAX_AUTO_PRIMARIES)
        .map(c => ({ name: c.name, pattern: c.pattern, source: 'auto', ...(c.equipment ? { equipment: c.equipment } : {}), ...(c.equipmentId ? { equipmentId: c.equipmentId } : {}) }));
}

/**
 * Template exercises with the user's main-lift choice applied (the Settings
 * picker): picked rows become role:'primary'; an un-picked former primary
 * drops back to what inference calls it — except a compound in the first two
 * slots, which would infer primary right back, so it's pinned 'secondary'.
 * @param {Array} exercises - template rows
 * @param {Set<string>} chosen - lowercased, trimmed exercise names
 * @returns {Array|null} null when nothing changed
 */
export function applyPrimaryChoice(exercises, chosen) {
    let changed = false;
    const out = (exercises || []).map((ex, idx) => {
        const name = norm(ex?.machine || ex?.name);
        if (!name) return ex;
        const want = chosen.has(name);
        if (want && ex.role !== 'primary') {
            changed = true;
            return { ...ex, role: 'primary' };
        }
        if (!want && ex.role === 'primary') {
            changed = true;
            const rest = { ...ex };
            delete rest.role;
            return inferRole(rest, idx) === 'primary' ? { ...rest, role: 'secondary' } : rest;
        }
        return ex;
    });
    return changed ? out : null;
}

/** Newest-first sessions of one lift: best e1RM and every set, in `unit`. */
function liftSessions(workouts, name, unit, today, machine = null) {
    const key = norm(name);
    const out = [];
    for (const w of workouts || []) {
        if (!usable(w, today) || isRecoveryWorkout(w)) continue;
        let found = null;
        eachExercise(w, (exName, ex) => {
            if (found || norm(exName) !== key) return;
            if (machine && !sameMachine(machine.name, machine.id, ex)) return; // AU-12
            const sets = strengthSets(ex)
                .map(s => ({ weight: loadOf(s, unit), reps: Number(s.reps) }))
                .filter(s => s.weight > 0);
            if (!sets.length) return;
            const e1rm = Math.max(0, ...sets.map(s => epley1RM(s.weight, s.reps)));
            found = { date: w.date, e1rm, sets, spelling: exName };
        });
        if (found) out.push(found);
    }
    out.sort((a, b) => b.date.localeCompare(a.date));
    return out;
}

/**
 * Best estimated 1RM for one lift between two dates (inclusive), recovery
 * sessions excluded — the block retrospective's start/end numbers (AP-23c).
 * @returns {number|null}
 */
export function bestE1rmBetween(workouts, name, unit, from, to, machine = null) {
    const vals = liftSessions(workouts, name, unit === 'kg' ? 'kg' : 'lbs', to, machine)
        .filter(s => s.date >= from && s.date <= to)
        .map(s => s.e1rm)
        .filter(v => v > 0);
    return vals.length ? Math.max(...vals) : null;
}

function trendOf(now, prev, increment) {
    if (!now || !prev) return null;
    const band = Math.max(prev * FLAT_BAND_PCT, increment);
    const d = now - prev;
    if (d > band) return 'up';
    if (d < -band) return 'down';
    return 'flat';
}

/**
 * A rep record at a load used before: the newest session's heaviest set
 * whose reps beat every earlier session at that same weight.
 */
function findRepPR(sessions, windowFrom) {
    const [latest, ...prior] = sessions;
    if (!latest || latest.date < windowFrom || !prior.length) return null;
    const bestAt = new Map();
    for (const s of prior) {
        for (const set of s.sets) {
            const k = round1(set.weight);
            bestAt.set(k, Math.max(bestAt.get(k) || 0, set.reps));
        }
    }
    let pr = null;
    for (const set of latest.sets) {
        const k = round1(set.weight);
        if (!bestAt.has(k) || set.reps <= bestAt.get(k)) continue;
        if (!pr || k > pr.weight || (k === pr.weight && set.reps > pr.reps)) {
            pr = { weight: k, reps: set.reps, prevReps: bestAt.get(k), date: latest.date };
        }
    }
    return pr;
}

function patternRows(workouts, today, target, mrv) {
    const c0From = shiftDay(today, -6);
    const c1From = shiftDay(today, -13);
    const c1To = shiftDay(today, -7);
    const rows = new Map(SPINE_PATTERNS.map(p => [p, { sets0: 0, sets1: 0, lastTrained: null }]));
    let rec0 = false;
    let rec1 = false;
    let historyStart = null;
    for (const w of workouts || []) {
        if (!usable(w, today)) continue;
        if (!historyStart || w.date < historyStart) historyStart = w.date;
        const rec = isRecoveryWorkout(w);
        const in0 = w.date >= c0From;
        const in1 = !in0 && w.date >= c1From && w.date <= c1To;
        if (rec && in0) rec0 = true;
        if (rec && in1) rec1 = true;
        eachExercise(w, (name, ex) => {
            // LB-1 — equipment-aware: Back Extension on the 45° bench is Hinge.
            const row = rows.get(inferPattern({ name }, { equipment: ex.equipment }));
            if (!row) return;
            const n = countableSets(ex);
            if (!n) return;
            if (!row.lastTrained || w.date > row.lastTrained) row.lastTrained = w.date;
            if (rec) return; // a deload's light week isn't a coverage gap
            if (in0) row.sets0 += n;
            else if (in1) row.sets1 += n;
        });
    }
    // The prior week only counts once history reaches back that far — a
    // one-week-old account hasn't been "under for two weeks".
    const priorCounts = !!historyStart && historyStart <= c1From;
    return SPINE_PATTERNS.map((pattern) => {
        const r = rows.get(pattern);
        let weeksUnder = 0;
        if (!rec0 && r.sets0 < target) {
            weeksUnder = 1;
            if (priorCounts && !rec1 && r.sets1 < target) weeksUnder = 2;
        }
        let status = 'in-range';
        if (rec0) status = 'recovery';
        else if (r.sets0 < target) status = 'under';
        else if (r.sets0 > mrv) status = 'over';
        return {
            pattern, label: PATTERN_LABELS[pattern],
            setsThisWeek: r.sets0, setsLastWeek: r.sets1,
            target, mrv, status, weeksUnder, lastTrained: r.lastTrained,
        };
    });
}

/** Stall rung and the AP-22 effort signal, from the same session list. */
function ladderAndFatigue(workouts, spelling, unit, inc, machine = null) {
    const sessions = buildExerciseSessions(workouts, spelling, unit, { machine });
    const f = fatigueState(sessions, { minSessions: RULE_THRESHOLDS.PLATEAU_MIN_SESSIONS, inc });
    return { rung: stallState(sessions).rung, fatigue: f?.fatigued ? f.reason : null };
}

function chooseHeadline(primaries, patterns, unit, target) {
    const down = primaries.find(p => p.downTwice);
    if (down) {
        return {
            kind: 'down',
            text: `${down.name} is down two 4-week windows running — estimated max ${down.e1rmPrev2} → ${down.e1rmPrev} → ${down.e1rmNow} ${unit}`,
        };
    }
    const gap = patterns.filter(p => p.weeksUnder >= 2).sort((a, b) => a.setsThisWeek - b.setsThisWeek)[0];
    if (gap) {
        return {
            kind: 'under',
            text: `${gap.label} has been under ${target} sets a week for 2 weeks — ${gap.setsThisWeek} in the last 7 days`,
        };
    }
    const trended = primaries.filter(p => p.trend === 'up' || p.trend === 'flat' || p.trend === 'down');
    if (trended.length) {
        const up = trended.filter(p => p.trend === 'up').length;
        return { kind: 'up', text: `${up} of ${trended.length} main lift${trended.length === 1 ? '' : 's'} up over 4 weeks` };
    }
    if (primaries.length) {
        return { kind: 'building', text: 'Trends show once your main lifts have 8 weeks of history' };
    }
    return { kind: 'none', text: '' };
}

/**
 * @param {object} args
 * @param {Array} args.workouts - history, any order (cancelled/incomplete skipped)
 * @param {Array} [args.templates] - workout templates (role:'primary' rows win)
 * @param {'lbs'|'kg'} [args.unit] - display unit; every number comes back in it
 * @param {string} args.today - YYYY-MM-DD (local)
 * @param {{patternTarget?:number, mrv?:number, increment?:number}} [args.config]
 *   patternTarget = weekly sets per movement pattern (default 16); mrv caps it
 * @returns {{unit:string, today:string, window:{from:string,to:string,prevFrom:string,prevTo:string},
 *   primaries:Array<{name:string, pattern:string|null, source:string, e1rmNow:number|null,
 *     e1rmPrev:number|null, e1rmPrev2:number|null, delta:number|null, deltaPct:number|null,
 *     trend:'up'|'flat'|'down'|'new'|'idle'|null, downTwice:boolean,
 *     repPR:{weight:number, reps:number, prevReps:number, date:string}|null,
 *     rung:number, lastDate:string|null}>,
 *   patterns:Array<{pattern:string, label:string, setsThisWeek:number, setsLastWeek:number,
 *     target:number, mrv:number, status:'under'|'in-range'|'over'|'recovery', weeksUnder:number,
 *     lastTrained:string|null}>,
 *   counts:{up:number, flat:number, down:number}, headline:string, headlineKind:string}}
 *   trend 'new' = trained this window only, 'idle' = not trained this window.
 */
export function buildScoreboard({ workouts = [], templates = [], unit = 'lbs', today, config = {} } = {}) {
    const u = unit === 'kg' ? 'kg' : 'lbs';
    const target = config.patternTarget ?? RULE_THRESHOLDS.PATTERN_TARGET_SETS;
    const mrv = config.mrv ?? RULE_THRESHOLDS.VOLUME_MRV;
    const increment = config.increment || INCREMENT[u];
    const days = SCOREBOARD_WINDOW_DAYS;
    const from = shiftDay(today, -(days - 1));
    const prevFrom = shiftDay(today, -(2 * days - 1));
    const prevTo = shiftDay(today, -days);
    const prev2From = shiftDay(today, -(3 * days - 1));
    const prev2To = shiftDay(today, -(2 * days));

    const primaries = pickPrimaries({ templates, workouts, today }).map((p) => {
        // AU-12 — a primary is an exercise ON a machine; fall back to the
        // name only when that machine has no history.
        let machine = p.equipment || p.equipmentId ? { name: p.equipment, id: p.equipmentId } : null;
        let sessions = liftSessions(workouts, p.name, u, today, machine);
        if (machine && !sessions.length) { machine = null; sessions = liftSessions(workouts, p.name, u, today); }
        const bestIn = (a, b) => {
            const vals = sessions.filter(s => s.date >= a && s.date <= b).map(s => s.e1rm).filter(v => v > 0);
            return vals.length ? Math.max(...vals) : null;
        };
        const now = bestIn(from, today);
        const prev = bestIn(prevFrom, prevTo);
        const prev2 = bestIn(prev2From, prev2To);
        let trend = trendOf(now, prev, increment);
        if (!trend && now) trend = 'new';
        else if (!trend && prev) trend = 'idle';
        const spelling = sessions[0]?.spelling || p.name;
        return {
            name: spelling,
            ...(machine?.name ? { equipment: machine.name } : {}),
            pattern: p.pattern,
            source: p.source,
            e1rmNow: now,
            e1rmPrev: prev,
            e1rmPrev2: prev2,
            delta: now && prev ? round1(now - prev) : null,
            deltaPct: now && prev ? round1(((now - prev) / prev) * 100) : null,
            trend,
            downTwice: trendOf(now, prev, increment) === 'down' && trendOf(prev, prev2, increment) === 'down',
            repPR: findRepPR(sessions, from),
            ...ladderAndFatigue(workouts, spelling, u, increment, machine),
            lastDate: sessions[0]?.date || null,
        };
    });

    const patterns = patternRows(workouts, today, target, mrv);
    const counts = { up: 0, flat: 0, down: 0 };
    for (const p of primaries) if (counts[p.trend] != null) counts[p.trend] += 1;
    const head = chooseHeadline(primaries, patterns, u, target);
    return {
        unit: u, today,
        window: { from, to: today, prevFrom, prevTo },
        primaries, patterns, counts,
        headline: head.text, headlineKind: head.kind,
    };
}

const TREND_WORDS = { up: 'up', flat: 'flat', down: 'down' };

/** One scoreboard row in words — shared by the coach block and the weekly review. */
export function describePrimary(p, unit) {
    const parts = [];
    if (TREND_WORDS[p.trend]) {
        const sign = p.delta > 0 ? '+' : '';
        parts.push(`estimated max ${p.e1rmNow} ${unit}, ${TREND_WORDS[p.trend]} ${sign}${p.delta} vs ${p.e1rmPrev} the 4 weeks before`);
    } else if (p.trend === 'new') {
        parts.push(`estimated max ${p.e1rmNow} ${unit}, no earlier window to compare`);
    } else if (p.trend === 'idle') {
        parts.push(`not trained in the last 4 weeks (estimated max was ${p.e1rmPrev} ${unit})`);
    } else {
        parts.push('no estimable sets (1–12 reps with a load)');
    }
    if (p.repPR) parts.push(`rep PR ${p.repPR.weight}×${p.repPR.reps} (was ×${p.repPR.prevReps}) on ${p.repPR.date}`);
    if (p.rung > 0) parts.push(describeStuck({ rung: p.rung }));
    if (p.fatigue) parts.push(p.fatigue);
    return `${p.name}${p.equipment ? ` on ${p.equipment}` : ''}: ${parts.join(' · ')}`;
}

/**
 * The scoreboard as context text for the coach and the weekly review.
 * @returns {string} '' when there is nothing to report
 */
export function formatScoreboardContext(sb) {
    if (!sb || (!sb.primaries.length && !sb.patterns.some(p => p.setsThisWeek || p.setsLastWeek))) return '';
    const lines = [`Progress scoreboard (best estimated max per 4-week window, lighter sessions excluded — the dashboard card shows these exact numbers; quote them, don't re-derive): ${sb.headline || 'no trend yet'}`];
    for (const p of sb.primaries) lines.push(`- ${describePrimary(p, sb.unit)}`);
    const target = sb.patterns[0]?.target ?? RULE_THRESHOLDS.PATTERN_TARGET_SETS;
    const mrv = sb.patterns[0]?.mrv ?? RULE_THRESHOLDS.VOLUME_MRV;
    const pat = sb.patterns.map((p) => {
        let s = p.status === 'recovery' ? 'lighter week' : p.status;
        if (p.weeksUnder >= 2) s += ' (2 weeks)';
        return `${p.label.toLowerCase()} ${p.setsThisWeek} ${s}`;
    });
    lines.push(`Movement patterns, sets in the last 7 days (target ${target}; more than ${mrv} is more than it can use): ${pat.join(' · ')}`);
    return `${lines.join('\n')}\n`;
}
