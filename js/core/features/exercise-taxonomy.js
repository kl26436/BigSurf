/** Movement label for a pattern, '' when there is none. */
export function movementLabel(pattern) {
    return (pattern && MOVEMENT_LABELS[pattern]) || '';
}

/** One stored bodyPart string → one of BODY_PARTS, or null. */
export function normalizeBodyPart(value) {
    if (value == null) return null;
    const key = String(value).trim().toLowerCase();
    if (!key) return null;
    if (Object.hasOwn(BODY_PART_ALIASES, key)) return BODY_PART_ALIASES[key];
    const exact = BODY_PARTS.find(b => b.toLowerCase() === key);
    return exact || null;
}

/** The focus tag a legacy bodyPart implied ('Calves' → 'calves'), else null. */
export function focusTagForBodyPart(value) {
    const key = String(value || '').trim().toLowerCase();
    return ALIAS_TAG[key] || null;
}

// The one name regex left — only for a name no pattern rule matches. Order
// matters: specific words before the generic ones they collide with
// ("lateral raise" before "lat", legs before the bare "press"), and \b on the
// short words so "cable" is not "ab".
const NAME_RULES = [
    [/\bbench\b|chest|\bfly\b|flye|\bpecs?\b|crossover/, 'Chest'],
    [/shoulder|\bdelts?\b|lateral raise/, 'Shoulders'],
    [/\brows?\b|pull|\blats?\b|\bback\b|deadlift|shrug|\btraps?\b/, 'Back'],
    [/glute|hip thrust/, 'Glutes'],
    [/squat|\blegs?\b|lunge|hamstring|\bquads?\b|calf|calves|thigh/, 'Legs'],
    [/\bpress\b/, 'Shoulders'],
    [/bicep|curl|tricep|\barms?\b|forearm|extension/, 'Arms'],
    [/\bcore\b|\babs?\b|abdominal|crunch|plank|oblique/, 'Core'],
    [/treadmill|\bbike\b|elliptical|rower|cardio|stair/, 'Cardio'],
];

/** Body part from the name alone (last resort), or null. */
export function bodyPartFromName(name) {
    const s = String(name || '').toLowerCase();
    if (!s.trim()) return null;
    for (const [re, part] of NAME_RULES) if (re.test(s)) return part;
    return null;
}

/** A conventional deadlift is filed under Back by convention, not Glutes. */
const BACK_DEADLIFT_RE = /deadlift/;
const NOT_BACK_DEADLIFT_RE = /romanian|\brdl\b|stiff/;

function bodyPartFromPattern(pattern, name) {
    if (!pattern) return null;
    if (pattern === 'hip-dominant' && BACK_DEADLIFT_RE.test(name) && !NOT_BACK_DEADLIFT_RE.test(name)) return 'Back';
    return PATTERN_BODY_PART[pattern] || null;
}

// Library lookups run per exercise per render; index each library array
// once (rebuilt when its length changes — the app replaces the array on
// reload, it doesn't mutate it).
const _index = new WeakMap();
function libraryIndex(library) {
    if (!Array.isArray(library) || library.length === 0) return null;
    const hit = _index.get(library);
    if (hit && hit.size === library.length) return hit.map;
    const map = new Map();
    for (const ex of library) {
        const key = String(ex?.name || ex?.machine || '').trim().toLowerCase();
        if (key && !map.has(key)) map.set(key, ex);
    }
    _index.set(library, { size: library.length, map });
    return map;
}

/** The library entry with this exact name (case-insensitive), or null. */
export function findInLibrary(name, library) {
    const key = String(name || '').trim().toLowerCase();
    if (!key) return null;
    return libraryIndex(library)?.get(key) || null;
}

function asExercise(exerciseOrName) {
    if (exerciseOrName == null) return null;
    if (typeof exerciseOrName === 'string') return { name: exerciseOrName };
    return exerciseOrName;
}

/**
 * THE body-part classifier. Chain: the bodyPart stored on the row → the
 * library entry's stored bodyPart → the movement pattern's body part (the
 * equipment can decide the pattern) → one name regex. Every step goes
 * through the alias map, so "Calves" is Legs and "General" defers.
 * @param {string|{name?:string, machine?:string, bodyPart?:string, tags?:string[], pattern?:string}} exerciseOrName
 * @param {{library?: object[], equipment?: string|object|null}} [opts]
 * @returns {string|null} one of BODY_PARTS, or null when nothing says
 */
export function canonicalBodyPart(exerciseOrName, { library = null, equipment = null } = {}) {
    const ex = asExercise(exerciseOrName);
    if (!ex) return null;
    const own = normalizeBodyPart(ex.bodyPart);
    if (own) return own;
    const name = String(ex.name || ex.machine || '').toLowerCase();
    const entry = findInLibrary(name, library);
    const stored = normalizeBodyPart(entry?.bodyPart);
    if (stored) return stored;
    const pattern = inferPattern(mergeLabels(entry, ex), { equipment });
    return bodyPartFromPattern(pattern, name) || bodyPartFromName(name);
}

/**
 * The group weekly volume is counted against — the dashboard cards and the
 * per-muscle weekly minimum/maximum. Glutes count with Legs (most glute work
 * in the library is filed under Legs; a separate Glutes line held only hip
 * thrusts to a weekly minimum — the same phantom "Calves volume low" was).
 * Cardio and unknown stay as they are; callers skip them.
 */
export function volumeGroup(bodyPart) {
    if (bodyPart === 'Glutes') return 'Legs';
    return bodyPart || null;
}

/**
 * The dashboard's body-part cards, in display order — BODY_PARTS through
 * volumeGroup, minus Cardio (conditioning has its own line; weight volume
 * means nothing for it).
 */
export const DASHBOARD_BODY_PARTS = ['chest', 'back', 'legs', 'shoulders', 'arms', 'core'];

/** Dashboard card key: 'chest' | 'back' | 'legs' | 'shoulders' | 'arms' | 'core' | 'cardio' | 'other'. */
export function dashboardBodyPart(bodyPart) {
    const g = volumeGroup(bodyPart);
    return g ? g.toLowerCase() : 'other';
}

// A library entry's labels under a row's own: the row's explicit pattern and
// non-empty tags win, the library fills the gaps.
function mergeLabels(entry, ex) {
    if (!entry) return ex;
    return {
        ...entry,
        ...ex,
        pattern: (PATTERNS.includes(ex?.pattern) && ex.pattern) || entry.pattern,
        tags: Array.isArray(ex?.tags) && ex.tags.length ? ex.tags : entry.tags,
    };
}

/**
 * Body part + movement for one exercise, the way every surface shows them.
 * @returns {{bodyPart: string|null, pattern: string|null, movement: string}}
 */
export function labelsFor(exerciseOrName, { library = null, equipment = null } = {}) {
    const ex = asExercise(exerciseOrName);
    if (!ex) return { bodyPart: null, pattern: null, movement: '' };
    const entry = findInLibrary(ex.name || ex.machine, library);
    const merged = mergeLabels(entry, ex);
    const pattern = inferPattern(merged, { equipment });
    return {
        bodyPart: canonicalBodyPart(ex, { library, equipment }),
        pattern,
        movement: movementLabel(pattern),
    };
}

/** "Legs · Hinge" — the body part and movement, whichever are known. */
export function labelLine(exerciseOrName, opts = {}) {
    const { bodyPart, movement } = labelsFor(exerciseOrName, opts);
    // "Cardio · Cardio" says it twice.
    return [bodyPart, movement !== bodyPart ? movement : ''].filter(Boolean).join(' · ');
}

/**
 * Apply a user's override of a built-in exercise. The override's fields win,
 * except labels it never set: an empty `tags` (every override saved before
 * LB-2 has one) keeps the built-in's tags, and a missing `pattern` keeps the
 * built-in's. Shared by the client library merge and the coach's
 * list_exercises so both see the same exercise.
 */
export function mergeExerciseOverride(exercise, override) {
    if (!override) return exercise;
    return {
        ...exercise,
        ...override,
        tags: Array.isArray(override.tags) && override.tags.length ? override.tags : (exercise?.tags || []),
        pattern: (PATTERNS.includes(override.pattern) && override.pattern) || exercise?.pattern || null,
    };
}

/**
 * The Movement choices to offer for a body part: its usual patterns first,
 * plus the current one if it lives elsewhere. `all` lists every pattern.
 * @returns {string[]}
 */
export function movementChoices(bodyPart, current = null, { all = false } = {}) {
    const base = all ? [...PATTERNS] : [...(BODY_PART_PATTERNS[normalizeBodyPart(bodyPart)] || PATTERNS)];
    if (current && PATTERNS.includes(current) && !base.includes(current)) base.push(current);
    return base;
}
