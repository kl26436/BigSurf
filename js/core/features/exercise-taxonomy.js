// Exercise taxonomy (LB-3 / LB-4) — ONE body-part vocabulary, ONE classifier,
// ONE table of movement labels.
//
// Before this there were four body-part classifiers (the exercise picker's
// exact-string filter, the Equipment Library's regex, the dashboard's
// aggregators fallback and training-rules' fallback) and they disagreed: a
// leg curl filed under Arms, a cable crossover under Core ("ab" in "cable"),
// calf raises dropped from the dashboard, "Calves" and "Abs" held to their
// own weekly minimum as if they were separate muscles. Every consumer now
// reads the stored label through this module; name inference is the fallback
// for unlabelled rows, not the primary path.
